	if (rising_edge(clk)) then
	    if (mb_IL_OP = IL_OP_from_interpreter) then
		    IL_OP <= il_codeByte;
	    end if;
 end if;
 end process;
		
 update_RetStack: process(clk, mb_RetStack)
 begin
	if (rising_edge(clk)) then
		case mb_RetStack is
--			when RetStack_same =>
--				RetStack <= RetStack;
			when RetStack_clear =>
				RetSP <= (others => '0');
			when RetStack_pop =>
				RetSP <= std_logic_vector(unsigned(RetSP) - 1);
			when RetStack_push_IL_PC_PLUS_1 =>
				RetStack(to_integer(unsigned(RetSP))) <= "00000" & std_logic_vector(unsigned(IL_PC) + 1);
				RetSP <= std_logic_vector(unsigned(RetSP) + 1);
			when others =>
				null;
		end case;
 end if;
 end process;
		
 update_BasStack: process(clk, mb_BasStack)
 begin
	if (rising_edge(clk)) then
		case mb_BasStack is
--			when BasStack_same =>
--				BasStack <= BasStack;
			when BasStack_clear =>
				BasSP <= (others => '0');
			when BasStack_pop =>
				BasSP <= std_logic_vector(unsigned(BasSP) - 1);
			when BasStack_push_Lino_and_BP =>
				-- push also the interrupt level to restore it with last RETURN in interrupt service routine
				BasStack(to_integer(unsigned(BasSP))) <= il_previous & Lino & BP; 
