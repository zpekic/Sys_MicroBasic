 is_pq <= '1' when (IL_OP = OP_PQ) else '0';
 hex_ascii <= hex2ascii(to_integer(unsigned(Y(31 downto 28))));
 
 update_CHAROUT: process(clk, mb_CHAROUT)
 begin
	if (rising_edge(clk)) then
		outchar_send <= CHAROUT_SEND;				-- delay send signal 1 clock cycle
		case mb_CHAROUT is
			when CHAROUT_same =>
				CHAROUT_SEND <= '0';					-- pulse low
				--CHAROUT <= CHAROUT;
			when CHAROUT_from_interpreter =>
				lz <= '1';
				CHAROUT_SEND <= '1';					-- pulse high when data loaded
				CHAROUT <= il_codeByte;
			when CHAROUT_from_microcode =>
				lz <= '1';
				CHAROUT_SEND <= '1';					-- pulse high when data loaded
				CHAROUT <= '0' & mb_directByte;	-- because we store only 7-bit ASCII in microcode
			when CHAROUT_from_charin =>
				lz <= '1';
				CHAROUT_SEND <= '1';					-- pulse high when data loaded
				CHAROUT <= CHARIN;
			when CHAROUT_from_MDR =>
				lz <= '1';
				if (caret_escape = '1') then
					-- escaping is on, always output a char and turn escaping off
					CHAROUT_SEND <= '1';
					caret_escape <= '0';				
					if ((MDR = CARET) or (MDR = CR)) then
						-- ^^ means we want to display the ^ and kill the escape mode
						CHAROUT <= MDR;
					else
						if (mdr_is_uppercase = '1') then
							-- ^ is followed by A..Z, this is now a control character!
							CHAROUT <= std_logic_vector(unsigned(MDR) - 64);
						else 
							-- escape has no effect on any other characters
							CHAROUT <= MDR;
						end if;
					end if;
				else
					-- check if is off, check if it needs to be turned on
					CHAROUT <= MDR;
					if (MDR = CARET) then
						-- detected 1st ^ in sequence, turn on escaping, no send pulse
						caret_escape <= is_pq;			-- escaping only works in PQ instruction
						CHAROUT_SEND <= not(is_pq);	-- only swallow if in PQ
					else
						-- any other char in
						caret_escape <= '0';
						CHAROUT_SEND <= '1';			
					end if;
				end if;
			when CHAROUT_from_YtoAlpha =>				-- from top nibble of Y register, including zero
				lz <= '1';
				CHAROUT_SEND <= '1';						-- pulse high when data loaded
				CHAROUT <= hex_ascii;
			when CHAROUT_from_YtoAlphaZ =>			-- from top nibble of Y register, supress leading zero
				if (Y(31 downto 28) = X"0") then
					if (lz = '0') then
						-- this is 0 but previous was not zero, so need to output
						CHAROUT_SEND <= '1';			  
						CHAROUT <= hex_ascii;
					end if;
				else
					-- not zero, so clear the leading zero flag to output subsequent zeroes
					CHAROUT_SEND <= '1';	
					CHAROUT <= hex_ascii;
					lz <= '0';
				end if;
			when others =>
				null;
		end case;
 end if;
 end process;
  
-- watch the output characters to update the TAB counter
on_charout_send: process(CHAROUT_SEND, reset)
begin
	if (reset = '1') then
		tab_cnt <= (others => '0');
	else
		if (rising_edge(CHAROUT_SEND)) then
			case CHAROUT is
				when CR =>	-- CR resets to left margin
					tab_cnt <= (others => '0');
				when BS => -- BS goes one space left
					tab_cnt <= std_logic_vector(unsigned(tab_cnt) - 1);
				when NUL => -- NULL does nothing
					null;
				when others => -- all other characters advance
					tab_cnt <= std_logic_vector(unsigned(tab_cnt) + 1);
			end case;
		end if;
	end if;
end process; 

