		data(63 downto 48) => BP,
		txd => debug_txd,
		ready => DBG_READY
		);
	
 update_DBGINDEX: process(clk, mb_DBGINDEX)
 begin
	if (rising_edge(clk)) then
		case mb_DBGINDEX is
--			when DBGINDEX_same =>
--				DBGINDEX <= DBGINDEX;
			when DBGINDEX_from_microcode =>
				DBGINDEX <= mb_directByte(5 downto 0);
				dbg_start <= '1';
			when DBGINDEX_zero =>
				DBGINDEX <= (others => '0');
				dbg_start <= '0';
			when DBGINDEX_crlf =>
				DBGINDEX <= (others => '1'); -- points to last index in the table
				dbg_start <= '1';
			when others =>
				null;
		end case;
 end if;
 end process;

-- ALU
 update_alu: process(clk, mb_alu)
 begin
	if (rising_edge(clk)) then
		case mb_alu is
--			when alu_nop =>
--				alu <= alu;
			when alu_reset =>
				R <= (others => '0');
				S <= (others => '0');
				alu_ready <= '0';
				alu_sign <= '0';
				alu_overflow <= '0';
			when alu_R_fromStack =>
				R(15 downto 8) <= ExpStack(to_integer(unsigned(ExpSP) - 2)); 
				R(7 downto 0) <= ExpStack(to_integer(unsigned(ExpSP) - 1)); 
			when alu_S_fromStack =>
				S(15 downto 8) <= ExpStack(to_integer(unsigned(ExpSP) - 2)); 
				S(7 downto 0) <= ExpStack(to_integer(unsigned(ExpSP) - 1)); 
			when alu_add =>
				Y <= X"0000" & r_plus_s;
				alu_ready <= '1';
				alu_sign <= r_plus_s(15);
				alu_overflow <= plus_overflow;
			when alu_sub =>
				Y <= X"0000" & s_minus_r;
				alu_ready <= '1';
				alu_sign <= s_minus_r(15);
				alu_overflow <= minus_overflow;
			when alu_neg =>
				Y <= X"0000" & neg_r;
				alu_ready <= '1';
				alu_sign <= neg_r(15);
				alu_overflow <= neg_overflow;
			when alu_mul =>
				Y <= r_mul_s;
				alu_ready <= '1';
				alu_sign <= r_mul_s(31);
				alu_overflow <= mul_overflow;
			when alu_bcd_start =>
				-- first step
				if (R(15) = '1') then
					alu_sign <= '1';
					R <= std_logic_vector(0 - signed(R));
				else
					alu_sign <= '0';
				end if;
				S <= (others => '0');	-- prepare counter for bit 0 of R
				Y <= (others => '0');	-- clear BCD accumulator
				alu_ready <= '0';
				alu_overflow <= '0';		-- by implementation can't overflow
			when alu_bcd_next =>
				Y <= bcd_sum & X"00";	-- we care about most significant 6 BCD digits
				if ((S = X"000F") or (R = X"0000")) then
					alu_ready <= '1';
				else
					alu_ready <= '0';
					S <= std_logic_vector(unsigned(S) + 1);
					R <= '0' & R(15 downto 1);	-- shift down
				end if;
				leading_zero <= '1';
			when alu_Yx16 =>
				-- microcode should execute this EXACTLY 6 times to pick up 6 BCD digits!
				Y <= Y(27 downto 0) & X"0";	-- shift up by a nibble (== BCD digit)
				if (Y(27 downto 24) = X"0") then
					leading_zero <= leading_zero;
				else
					leading_zero <= '0';
				end if;
			when alu_div_start =>	-- R / S 
				alu_overflow <= '0';	-- By definition can't overflow
				alu_ready <= '0';
				if (S(15) = '0') then
					-- S > 0
					-- NOTE: before this step, S is already checked for 0 (divide by 0 condition)
					if (R(15) = '0') then
						-- R >= 0
						R <= neg_r;	-- we need the -R for subtraction
						alu_sign <= '0';	-- +/+
					else
						-- R < 0, already good for substraction
						alu_sign <= '1';	-- -/+
					end if;
					Y <= X"0000" & S;
					S <= X"000F";	-- S will be the 16 steps counter 
				else
					-- S < 0
					if (R(15) = '0') then
						-- R >= 0
						R <= neg_r;	-- we need the -R for subtraction
						alu_sign <= '1';	-- +/-
					else
						-- R < 0
						alu_sign <= '0';	-- -/-
					end if;
					Y <= X"0000" & neg_s;
					S <= X"000F";	-- S will be the 16 steps counter 
				end if;				
			when alu_div_shift =>
				Y <= Y(30 downto 0) & '0'; -- shift remainder and quotient up
				alu_ready <= '0';
			when alu_div_subset =>
				if (S = X"0000") then
					alu_ready <= '1';	-- done!
				else	
					S <= std_logic_vector(unsigned(S) - 1);
					alu_ready <= '0';	-- continue
					if (sub(16) = '0') then
						Y <= Y(31 downto 1) & '0';
					else
						Y <= sub(15 downto 0) & Y(15 downto 1) & '1';
					end if;
				end if;
			when alu_div_end =>
				if (alu_sign = '1') then
					-- correct quotient sign
					Y(15 downto 0) <= neg_y;
				end if;
			when others =>
				null;
		end case;
 end if;
 end process;

-- 17 bit subtract for division step
sub <= std_logic_vector(unsigned('0' & Y(31 downto 16)) + unsigned('0' & R));

-- 6 digit BCD adder
adder: entity work.bcdadder Port map (
		power => S(3 downto 0),
		sel => R(0),
		sum_in => Y(31 downto 8),
		sum_out => bcd_sum
		);
 
-- combinatorial operations
r_plus_s <= std_logic_vector(signed(R) + signed(S));
plus_overflow <= ((not R(15)) and (not S(15))) when (r_plus_s(15) = '1') else (R(15) and S(15));

s_minus_r <= std_logic_vector(signed(S) - signed(R));
minus_overflow <= '0';

neg_r <= std_logic_vector(0 - signed(R));
neg_overflow <= '1' when (R = X"8000") else '0';	-- can't negate -32768

neg_s <= std_logic_vector(0 - signed(S));
neg_y <= std_logic_vector(0 - signed(Y(15 downto 0)));

-- will use intrinsic multiplier on FPGA (which is also combinatorial, therefore this is sintesizable)
r_mul_s <= std_logic_vector(signed(R) * signed(S));
mul_pos16 <= '1' when (r_mul_s(31 downto 15) = (X"0000" & '0')) else '0';
mul_neg16 <= '1' when (r_mul_s(31 downto 15) = (X"FFFF" & '1')) else '0';
mul_overflow <= not(mul_pos16 or mul_neg16);

