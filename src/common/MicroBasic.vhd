-- input character
on_inchar_ready: process(reset, inchar_ready, mb_gotChar)
begin
	if ((reset or mb_gotChar) = '1') then
		--CHARIN <= (others => '0');
		charin_ready <= '0';
	else
		if (rising_edge(inchar_ready)) then
			CHARIN <= inchar;
			charin_ready <= '1';
		end if;
	end if;
end process;
	
