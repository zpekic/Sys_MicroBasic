update_IL_PC: process(clk, mb_IL_PC)
 begin
	if (rising_edge(clk)) then
		case mb_IL_PC is
--			when IL_PC_same =>
--				IL_PC <= IL_PC;
			when IL_PC_zero =>
				IL_PC <= (others => '0');
			when IL_PC_inc =>
				IL_PC <= std_logic_vector(unsigned(IL_PC) + 1);
			when IL_PC_T =>
				IL_PC <= T(10 downto 0);
			when IL_PC_pc_plus_off6 =>
				-- a bit bizarre offset
				IL_PC <= std_logic_vector(unsigned(IL_PC) + unsigned(IL_OP) - 96);
			when IL_PC_pc_plus_off5 =>
				-- can only jump forward
				IL_PC <= std_logic_vector(unsigned(IL_PC) + unsigned(IL_OP5));
			when IL_PC_direct11 =>
				-- top 3 bits from IL_OP, lower 8 from code pointed by IL
				IL_PC <= IL_OP(2 downto 0) & il_codeByte;
			when IL_PC_RetStack =>
				-- RetSP points to first free location
				-- we cannot modify RetSP here, so must be combined with "pop" operation on RetStack
				IL_PC <= RetStack(to_integer(unsigned(RetSP) - 1));
			when others =>
				null;
		end case;
 end if;
end process;

 update_XQhere: process(clk, mb_XQhere)
 begin
	if (rising_edge(clk)) then
	    if (mb_XQhere = XQhere_T) then
		    XQhere <= T(10 downto 0);
	    end if;
 end if;
 end process;

 update_IL_OP: process(clk, mb_IL_OP)
 begin
	if (rising_edge(clk)) then
	    if (mb_IL_OP = IL_OP_from_interpreter) then
		    IL_OP <= il_codeByte;
	    end if;
 end if;
 end process;
		
 update_RetStack: process(clk, mb_RetStack)
 begin
	if (rising_edge(clk)) then
		case mb_RetStack is
--			when RetStack_same =>
--				RetStack <= RetStack;
			when RetStack_clear =>
				RetSP <= (others => '0');
			when RetStack_pop =>
				RetSP <= std_logic_vector(unsigned(RetSP) - 1);
			when RetStack_push_IL_PC_PLUS_1 =>
				RetStack(to_integer(unsigned(RetSP))) <= std_logic_vector(unsigned(IL_PC) + 1);
				RetSP <= std_logic_vector(unsigned(RetSP) + 1);
			when others =>
				null;
		end case;
 end if;
 end process;
		
update_T: process(clk, mb_T)
begin
	if (rising_edge(clk)) then
		case mb_T is
--			when T_same =>
--				T <= T;
			when T_IL_PC =>
				T <= "00000" & IL_PC;
			when T_XQhere =>
				T <= "00000" & XQhere;
			when T_from_vars =>
				T <= vars(to_integer(unsigned(vars_index(4 downto 0))));
			when T_ExpStack =>
				T <= ExpSTHi & ExpSTLo;
			when T_from_Y =>
				T <= Y(15 downto 0);
			when T_codeByte =>
				T <= X"00" & il_codeByte;	
			when T_MDRx2 =>	
				-- assume it is already uppercased, otherwise a and A would be different variables!
				T <= X"00" & MDR(6 downto 0) & '0';
			when T_inc =>
				T <= std_logic_vector(unsigned(T) + 1);
			when T_dec =>
				T <= std_logic_vector(unsigned(T) - 1);
			when T_BP =>
				T <= BP;
			when T_Prog_start =>
				T <= Prog_Start;
			when T_PrgEnd =>
				T <= PrgEnd;	
			when T_from_S =>
				T <= S;
			when T_from_R =>
				T <= R;
			when others =>
				null;
		end case;
 end if;
end process;
	
