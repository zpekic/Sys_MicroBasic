-- ALU (including R, S, Y and various bit-state registers)
--------------------------------------------------------------
 update_alu: process(clk, mb_alu)
 begin
	if (rising_edge(clk)) then
		-- clear cache valid bits at start of run (when Lino goes from 0 to some valid Basic line number)
		lino_clk <= Lino;
		if ((is_runmode = '1') and (lino_clk = X"0000")) then
			cache_valid <= (others => '0');
		end if;
		case mb_alu is
--			when alu_nop =>
--				alu <= alu;
			when alu_reset0 =>
				R <= (others => '0');
				Y_saved <= (others => '0');
				S <= (others => '0');
				Y <= (others => '0');
				alu_ready <= '0';
				alu_overflow <= '0';
			when alu_reset1 =>
				R <= (others => '1');
				Y_saved <= (others => '0');
				S <= (others => '0');
				--Y <= (others => '0');
				alu_ready <= '0';
				alu_overflow <= '0';
			when alu_R_fromStack =>
				R <= ExpSTHi & ExpSTLo; 
			when alu_S_fromStack =>
				S <= ExpSTHi & ExpSTLo; 
			when alu_S_plus_R =>
				Y <= X"0000" & s_plus_r;
				alu_ready <= '1';
				alu_overflow <= plus_overflow;
			when alu_S_minus_R =>
				Y <= X"0000" & s_minus_r;
				alu_ready <= '1';
				alu_overflow <= minus_overflow;
			when alu_neg_R =>
				Y <= X"0000" & neg_r;
				alu_ready <= '1';
				alu_overflow <= neg_overflow;
			when alu_S_mul_R =>
				Y <= s_mul_r;
				alu_ready <= '1';
				alu_overflow <= mul_overflow;
			when alu_Yx16 =>
				-- microcode should execute this EXACTLY 7 times to pick up 8 BCD digits!
				Y <= Y(27 downto 0) & X"0";	-- shift up by a nibble (== BCD digit)
			when alu_bcd_start =>
				-- first step
				if (R(15) = '1') then
					alu_sign <= '1';
					R <= neg_R;				-- BUGBUG -32768??
				else
					alu_sign <= '0';
				end if;
				S <= (others => '0');	-- prepare counter for bit 0 of R
				Y <= (others => '0');	-- clear BCD accumulator
				alu_ready <= '0';
				alu_overflow <= '0';		-- by implementation can't overflow
			when alu_bcd_next =>
				Y <= X"00" & bcd_sum;	-- 16-bit binary needs 6 BCD digits, so zero out high byte
				if ((S = X"000F") or (R = X"0000")) then
					alu_ready <= '1';
				else
					alu_ready <= '0';
					S <= std_logic_vector(unsigned(S) + 1);
					R <= '0' & R(15 downto 1);	-- shift down
				end if;
			when alu_div_start =>	-- S / R 
				if (S(15) = '0') then
					-- S > 0
					-- NOTE: before this step, R is already checked for 0 (divide by 0 condition)
					if (R(15) = '0') then
						-- R >= 0
						R <= neg_r;	-- we need the -R for subtraction
						alu_sign <= '0';	-- +/+
					else
						-- R < 0, already good for substraction
						alu_sign <= '1';	-- -/+
					end if;
					Y <= X"0000" & S;
				else
					-- S < 0
					if (R(15) = '0') then
						-- R >= 0
						R <= neg_r;	-- we need the -R for subtraction
						alu_sign <= '1';	-- +/-
					else
						-- R < 0
						alu_sign <= '0';	-- -/-
					end if;
					Y <= X"0000" & neg_s;
				end if;				
				alu_overflow <= '0';	-- By definition can't overflow
				alu_ready <= '0';
				S <= X"0010";	-- use S as the 16 steps counter 
			when alu_div_shift =>
				if (S = X"0000") then
					alu_ready <= '1';
				else
					Y <= Y(30 downto 0) & '0'; -- shift remainder and quotient up
					alu_ready <= '0';
				end if;
			when alu_div_subset =>
				if (S = X"0000") then
					alu_ready <= '1';
				else 
					S <= std_logic_vector(unsigned(S) - 1);
					alu_ready <= '0';	-- continue
					if (subc(16) = '0') then
						Y <= Y(31 downto 1) & '0';
					else
						Y <= subc(15 downto 0) & Y(15 downto 1) & '1';
					end if;
				end if;
			when alu_div_end =>
				if (alu_sign = '1') then
					-- correct quotient sign
					Y(15 downto 0) <= neg_y;
				end if;
			when alu_Yx10_plus_MDR =>
				-- used for string to numeric conversion
				Y <=  std_logic_vector((10 * unsigned(Y(15 downto 0))) + (unsigned(MDR) - 48));
				if (Y(31 downto 16) = X"0000") then	-- BUGBUG, this is checked one cycle late
					alu_overflow <= '0';
				else
					alu_overflow <= '1';
				end if;
			when alu_Rx256_plus_MDR =>
				-- used for 2 bytes searches in memory
				R <= R(7 downto 0) & MDR;
			when alu_S_fromT =>
				S <= T;
			when alu_R_fromT =>
				R <= T;
			when alu_S_fromLino =>
				S <= Lino;
			when alu_copy_del =>
				S <= std_logic_vector(unsigned(LE) + 1);
				R <= LS;
				Y <= X"0000" & std_logic_vector(unsigned(PrgEnd) - unsigned(LE));
			when alu_copy_inc =>
				S <= std_logic_vector(unsigned(S) + 1);
				R <= std_logic_vector(unsigned(R) + 1);
				Y <= std_logic_vector(unsigned(Y) - 1);
			when alu_ls_load =>
				-- initialize for LS (list) opcode
				-- S = start line, R = end line, store both to Y and check values
				if (S = X"FFFF") then
					-- 1 param given on command line, so start and end should be that
					Y <= R & R;				
					ls_params_ok <= '1';					
				else 
					if (R = X"FFFF") then
						-- no parameters? assume full range
						Y <= S & R;
						ls_params_ok <= '1';
					else
						-- two or no params on command line, check that start <= end
						if (unsigned(R) <= unsigned(S)) then
							Y <= R & S;
							ls_params_ok <= '1';
						else
							ls_params_ok <= '0';
						end if;
					end if;
				end if;
			when alu_ls_check =>
				-- check if current line with number R is in range previously saved in Y
				if (unsigned(R) > unsigned(ListTo)) then
					ls_passed_end <= '1';
					ls_in_range <= '0';
				else
					ls_passed_end <= '0';
					if (unsigned(R) >= unsigned(ListFrom)) then
						ls_in_range <= '1';
					else
						ls_in_range <= '0';
					end if;
				end if;
			when alu_Y_save =>
				Y_saved <= Y;
			when alu_Y_recall => 
				Y <= Y_saved;
			when alu_Y_fromTicks =>
				Y <= cnt_tick;
			when alu_cache_store =>
				cache(to_integer(unsigned(Lino_index))) <= BP & Lino;
				cache_valid(to_integer(unsigned(Lino_index))) <= '1';
			when others =>
				null;
		end case;
 end if;
 end process;

-- 17 bit subtract for division step
subc <= std_logic_vector(unsigned('0' & Y(31 downto 16)) + unsigned('0' & R));

