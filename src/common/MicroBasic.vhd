-- ALU
 update_alu: process(clk, mb_alu)
 begin
	if (rising_edge(clk)) then
		case mb_alu is
--			when alu_nop =>
--				alu <= alu;
			when alu_reset =>
				R <= (others => '0');
				S <= (others => '0');
				alu_ready <= '0';
				alu_sign <= '0';
				alu_overflow <= '0';
				alu_divby0 <= '0';
			when alu_R_fromStack =>
				R(15 downto 8) <= ExpStack(to_integer(unsigned(ExpSP) - 2)); 
				R(7 downto 0) <= ExpStack(to_integer(unsigned(ExpSP) - 1)); 
			when alu_S_fromStack =>
				S(15 downto 8) <= ExpStack(to_integer(unsigned(ExpSP) - 2)); 
				S(7 downto 0) <= ExpStack(to_integer(unsigned(ExpSP) - 1)); 
			when alu_add =>
				Y <= X"00" & r_plus_s;
				alu_ready <= '1';
				alu_sign <= r_plus_s(15);
				alu_overflow <= plus_overflow;
			when alu_sub =>
				Y <= X"00" & r_minus_s;
				alu_ready <= '1';
				alu_sign <= r_minus_s(15);
				alu_overflow <= minus_overflow;
			when alu_neg =>
				Y <= X"00" & neg_r;
				alu_ready <= '1';
				alu_sign <= neg_r(15);
				alu_overflow <= neg_overflow;
			when alu_mul =>
				Y <= X"00" & r_mul_s(15 downto 0);
				alu_ready <= '1';
				alu_sign <= r_mul_s(31);
				alu_overflow <= mul_overflow;
			when alu_div =>
				--Y <= ???
				alu_ready <= '0';		-- TODO! Stuck on purpose
				alu_sign <= '0';		-- TODO
				alu_overflow <= '0';	-- By definition can't overflow
				alu_divby0 <= '1';
			when alu_bcd_start =>
				-- first step
				if (R(15) = '1') then
					alu_sign <= '1';
					R <= std_logic_vector(0 - signed(R));
				else
					alu_sign <= '0';
				end if;
				S <= (others => '0');	-- prepare counter for bit 0 of R
				Y <= (others => '0');	-- clear BCD accumulator
				alu_ready <= '0';
				alu_overflow <= '0';	-- by implementation can't overflow
			when alu_bcd_next =>
				Y <= bcd_sum;
				if ((S = X"000F") or (R = X"0000")) then
					alu_ready <= '1';
				else
					alu_ready <= '0';
					S <= std_logic_vector(unsigned(S) + 1);
					R <= '0' & R(15 downto 1);	-- shift down
				end if;
			when alu_Yx16 =>
				Y <= Y(19 downto 0) & X"0";	-- shift up by a nibble (== BCD digit)
			when others =>
				null;
		end case;
 end if;
 end process;

-- 6 digit BCD adder
adder: entity work.bcdadder Port map (
		power => S(3 downto 0),
		sel => R(0),
		sum_in => Y,
		sum_out => bcd_sum
		);
 
-- combinatorial operations (including signed mul!)
r_plus_s <= std_logic_vector(signed(R) + signed(S));
plus_overflow <= '0';

r_minus_s <= std_logic_vector(signed(R) - signed(S));
minus_overflow <= '0';

neg_r <= std_logic_vector(0 - signed(R));
neg_overflow <= '1' when (R = X"8000") else '0';	-- can't negate -32768

-- will use intrinsic multiplier on FPGA
