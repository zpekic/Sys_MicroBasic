architecture Behavioral of MicroBasic is

type ram16x8 is array (0 to 15) of std_logic_vector(7 downto 0);
type ram8x11 is array (0 to 7) of std_logic_vector(10 downto 0);

-- control unit
signal ui_address: std_logic_vector(CODE_ADDRESS_WIDTH - 1 downto 0);
signal ui_nextinstr: std_logic_vector(CODE_ADDRESS_WIDTH -1  downto 0);

-- Intermediate languge
signal IL_PC: std_logic_vector(10 downto 0); -- 9 bits enough, but keep it compatible with other implementations
signal IL_OP: std_logic_vector(7 downto 0);
alias IL_OP5: std_logic_vector(4 downto 0) is IL_OP(4 downto 0);
signal IL_PC_VALID: std_logic;
signal il_codeByte: std_logic_vector(7 downto 0);
signal off_is_zero: std_logic;

-- single char output
signal CHAROUT: std_logic_vector(7 downto 0);
signal CHAROUT_SEND, CHAROUT_READY: std_logic;

-- single char input
signal CHARIN: std_logic_vector(7 downto 0);
signal charin_equ_db, charin_printable, charin_ready: std_logic; 

-- serial debug port
signal DBGINDEX: std_logic_vector(5 downto 0); -- 64 entries supported
signal DBG_READY, dbg_start: std_logic;

-- external memory related
signal MAR: std_logic_vector(15 downto 0);
signal MDR: std_logic_vector(7 downto 0);
signal mdr_equ_db, mdr_is_num, mdr_is_alpha, mdr_is_lowercase, mdr_is_uppercase, mdr_matches_ilcodebyte: std_logic;

-- key pointers
signal BP, SvPt, BP_temp: std_logic_vector(15 downto 0);
signal bp_in_inpline, svp_in_inpline: std_logic;
constant Inline_Start: std_logic_vector(15 downto 0) := X"0000"; -- TODO 
constant Inline_End: std_logic_vector(15 downto 0) := X"00FF"; -- TODO 
signal InlEnd: std_logic_vector(15 downto 0);
signal inlend_max, inlend_min: std_logic;

-- expression stack, 16 bytes == 8 words, SP point to free byte
signal ExpStack: ram16x8;
signal ExpSP: std_logic_vector(3 downto 0);
signal ExpSwapR, ExpSwapS: std_logic_vector(3 downto 0);	-- pointers used in SX IL instruction
signal estack_is_full, estack_is_empty: std_logic;
signal SwapR, SwapS: std_logic_vector(7 downto 0);

-- IL return stack
signal RetStack: ram8x11;
signal RetSP: std_logic_vector(2 downto 0);
signal rstack_is_empty, rstack_is_full: std_logic;

-- ALU
signal bcd_sum: std_logic_vector(23 downto 0);	-- 24 bits to contain BCD digits e.g. 032767
signal Y: std_logic_vector(31 downto 0);			-- double size needed for MUL, DIV
signal R, S: std_logic_vector(15 downto 0);		-- ALU input arguments are 16 bit
signal r_plus_s, s_minus_r, neg_r, neg_s, neg_y: std_logic_vector(15 downto 0);
signal r_mul_s: std_logic_vector(31 downto 0);	-- output of combinatorial multiplier
signal sub: std_logic_vector(16 downto 0);		-- 17 bits, MSB is carry out which we need 
signal alu_sign, alu_overflow, alu_ready, r_is_zero, leading_zero: std_logic;
signal plus_overflow, minus_overflow, neg_overflow, mul_overflow, mul_pos16, mul_neg16: std_logic;

-- other
signal T: std_logic_vector(15 downto 0);
signal tab_cnt: std_logic_vector(7 downto 0);
signal at_tab: std_logic;
signal T10_plus_mdr: std_logic_vector(31 downto 0);

begin

nBUSREQ <= mb_nBUSREQ;
-- Tristate system bus
nRD <= mb_nRD when (nBUSACK = '0') else 'Z';
nWR <= mb_nWR when (nBUSACK = '0') else 'Z';

ABUS <= MAR when (nBUSACK = '0') else "ZZZZZZZZZZZZZZZZ";
update_MAR: process(clk, mb_MAR)
begin
	if (rising_edge(clk)) then
		case mb_MAR is
	--			when MAR_same =>
	--				MAR <= MAR;
			when MAR_InlEnd =>
				MAR <= InlEnd;
			when MAR_BP =>
				MAR <= BP;
			when others =>
				null;
		end case;
	end if;
end process;

DBUS <= MDR when ((mb_nWR or nBUSACK) = '0') else "ZZZZZZZZ";
update_MDR: process(clk, mb_MDR)
begin
	if (rising_edge(clk)) then
		case mb_MDR is
	--			when MDR_same =>
	--				MDR <= MDR;
			when MDR_from_Bus =>
				MDR <= DBUS;
			when MDR_zero =>
				MDR <= (others => '0');
			when MDR_CHARIN =>
				MDR <= CHARIN;
			when MDR_ToUpper =>
				-- only touch lowercase a-z and convert to A-Z
				if (mdr_is_lowercase = '1') then
					MDR <= std_logic_vector(unsigned(MDR) - 32);
				end if;
			when others =>
				null;
		end case;
	end if;
end process;

-- ROM containing the IL language instructions
cu_il: entity work.il_rom Port map ( 
		a => IL_PC,
      d => il_codeByte,
		a_is_valid => IL_PC_VALID
		);

-- mapping IL opcode to microcode routine start
mb_instructionstart <= mb_mapper(to_integer(unsigned(il_op)));

-- control unit
cu_mb: entity work.microbasic_control_unit
     Generic map (
			CODE_DEPTH => CODE_ADDRESS_WIDTH,
			IF_WIDTH => CODE_IF_WIDTH
     )
     Port map ( 
			-- standard inputs
			reset => reset,
			clk => clk,
			-- design specific inputs
			seq_cond => mb_seq_cond,
			seq_then => mb_seq_then,
			seq_else => mb_seq_else,
			seq_fork => mb_instructionstart(8 downto 0),	-- IL opcode mapper input
			-- condition bits
			cond(seq_cond_true) => '1',
			cond(seq_cond_ILCODEBYTE_BIT7) => il_codebyte(7),
			cond(seq_cond_CHAROUT_READY) => outchar_ready,
			cond(seq_cond_IL_PC_VALID) => IL_PC_VALID,
			cond(seq_cond_DBG_READY) => DBG_READY,
			cond(seq_cond_MDR_EQU_DB) => mdr_equ_db,
			cond(seq_cond_nBUSACK) => nBUSACK,
			cond(seq_cond_INLEND_MAX) => inlend_max,
			cond(seq_cond_INLEND_MIN) => inlend_min,
			cond(seq_cond_CHARIN_PRINTABLE) => charin_printable,
			cond(seq_cond_CHARIN_EQU_DB) => charin_equ_db,
			cond(seq_cond_CHARIN_READY) => charin_ready,
			cond(seq_cond_BP_IN_INPLINE) => bp_in_inpline,
			cond(seq_cond_SVP_IN_INPLINE) => svp_in_inpline,
			cond(seq_cond_MDR_IS_NUM) => mdr_is_num,
			cond(seq_cond_MDR_IS_ALPHA) => mdr_is_alpha,
			cond(seq_cond_ESTACK_IS_FULL) => estack_is_full,
			cond(seq_cond_ESTACK_IS_EMPTY) => estack_is_empty,
			cond(seq_cond_MDR_MATCHES_ILCODEBYTE) => mdr_matches_ilcodebyte,
			cond(seq_cond_RSTACK_IS_FULL) => rstack_is_full,
			cond(seq_cond_RSTACK_IS_EMPTY) => rstack_is_empty,
			cond(seq_cond_ALU_READY) => alu_ready,
			cond(seq_cond_ALU_OVERFLOW) => alu_overflow,
			cond(seq_cond_ALU_SIGN) => alu_sign,
			cond(seq_cond_R_IS_ZERO) => r_is_zero,
			cond(seq_cond_AT_TAB) => at_tab,
			cond(seq_cond_OFF_IS_ZERO) => off_is_zero,
			cond(seq_cond_LEADING_ZERO) => leading_zero,
			cond(seq_cond_cond28) => '1',
			cond(seq_cond_cond29) => '1',
			cond(seq_cond_cond30) => '1',
			cond(seq_cond_false) => '0',
			-- outputs
			ui_nextinstr => ui_nextinstr,
			ui_address => ui_address
		);

mdr_matches_ilcodebyte <= '1' when (MDR(6 downto 0) = il_codeByte(6 downto 0)) else '0'; -- TODO: make it case insensitive!
mdr_equ_db <=			'1' when (MDR = mb_directByte) else '0';
mdr_is_num <=			'1' when ((unsigned(MDR) > 47) and (unsigned(MDR) < 58)) else '0';
mdr_is_lowercase <=	'1' when ((unsigned(MDR) > 96) and (unsigned(MDR) < 123)) else '0';
mdr_is_uppercase <=	'1' when ((unsigned(MDR) > 64) and (unsigned(MDR) < 91)) else '0';
mdr_is_alpha <= 		mdr_is_lowercase or mdr_is_uppercase;
estack_is_full <= 	'1' when (ExpSP = X"F") else '0';
estack_is_empty <=	'1' when (ExpSP = X"0") else '0';
charin_equ_db <=		'1' when (CHARIN = mb_directByte) else '0';
charin_printable <=	'0' when (CHARIN(7 downto 5) = "000") else (not CHARIN(7)); -- TODO: Add 0x7F 
inlend_max <=			'1' when (InlEnd = InLine_End) else '0';
inlend_min <=			'1' when (InlEnd = InLine_Start) else '0';
bp_in_inpline <=		'1' when ((unsigned(BP) >= unsigned(InLine_Start)) and (unsigned(BP) <= unsigned(InLine_End))) else '0';
svp_in_inpline <=		'1' when ((unsigned(SvPt) >= unsigned(InLine_Start)) and (unsigned(SvPt) <= unsigned(InLine_End))) else '0';
rstack_is_full	<=		'1' when (RetSP = "111") else '0';
rstack_is_empty <=	'1' when (RetSP = "000") else '0';
at_tab <= 				'1' when (tab_cnt(2 downto 0) = "000") else '0';
r_is_zero <= 			'1' when (R = X"0000") else '0';
off_is_zero	<=			'1' when (IL_OP(4 downto 0) = "00000") else '0';

-- get the microcode instruction 
mb_uinstruction <= mb_microcode(to_integer(unsigned(ui_address)));
		
update_IL_PC: process(clk, mb_IL_PC)
 begin
	if (rising_edge(clk)) then
		case mb_IL_PC is
--			when IL_PC_same =>
--				IL_PC <= IL_PC;
			when IL_PC_zero =>
				IL_PC <= (others => '0');
			when IL_PC_inc =>
				IL_PC <= std_logic_vector(unsigned(IL_PC) + 1);
			when IL_PC_T =>
				IL_PC <= T(10 downto 0);
			when IL_PC_pc_plus_off6 =>
				-- a bit bizarre offset
				--if (IL_OP(5) = '1') then
				--	IL_PC <= std_logic_vector(unsigned(IL_PC) + unsigned(IL_OP5));
				--else
				--	IL_PC <= std_logic_vector(unsigned(IL_PC) - unsigned(IL_OP5));
				--end if;
				IL_PC <= std_logic_vector(unsigned(IL_PC) + unsigned(IL_OP) - 96);
			when IL_PC_pc_plus_off5 =>
				-- can only jump forward
				IL_PC <= std_logic_vector(unsigned(IL_PC) + unsigned(IL_OP5));
			when IL_PC_direct11 =>
				-- top 3 bits from IL_OP, lower 8 from code pointed by IL
				IL_PC <= IL_OP(2 downto 0) & il_codeByte;
			when IL_PC_RetStack =>
				-- RetSP points to first free location
				-- we cannot modify RetSP here, so must be combined with "pop" operation on RetStack
				IL_PC <= RetStack(to_integer(unsigned(RetSP) - 1));
			when others =>
				null;
		end case;
 end if;
end process;
		
 update_RetStack: process(clk, mb_RetStack)
 begin
	if (rising_edge(clk)) then
		case mb_RetStack is
--			when RetStack_same =>
--				RetStack <= RetStack;
			when RetStack_clear =>
				RetSP <= (others => '0');
			when RetStack_pop =>
				RetSP <= std_logic_vector(unsigned(RetSP) - 1);
			when RetStack_push_IL_PC_PLUS_1 =>
				RetStack(to_integer(unsigned(RetSP))) <= std_logic_vector(unsigned(IL_PC) + 1);
				RetSP <= std_logic_vector(unsigned(RetSP) + 1);
			when others =>
				null;
		end case;
 end if;
 end process;

 update_IL_OP: process(clk, mb_IL_OP)
 begin
	if (rising_edge(clk)) then
	    if (mb_IL_OP = IL_OP_from_interpreter) then
		    IL_OP <= il_codeByte;
	    end if;
 end if;
 end process;
		
update_T: process(clk, mb_T)
begin
	if (rising_edge(clk)) then
		case mb_T is
--			when T_same =>
--				T <= T;
			when T_IL_PC =>
				T <= "00000" & IL_PC;
			when T_zero =>
				T <= (others => '0');
			when T_T10_plus_mdr =>
				T <= T10_plus_mdr(15 downto 0);		
			when T_from_alu =>
				T <= Y(15 downto 0);
			when others =>
				null;
		end case;
 end if;
end process;

-- will generate 32 bits (16 x 16)
T10_plus_mdr <= std_logic_vector(10 * unsigned(T) + (unsigned(MDR) - 48));
	
 update_BP: process(clk, mb_BP)
 begin
	if (rising_edge(clk)) then
		case mb_BP is
--			when BP_same =>
--				BP <= BP;
			when BP_InLine_start =>
				BP <= InLine_Start;
			when BP_SvPt =>
				BP <= SvPt;
			when BP_inc =>
				BP <= std_logic_vector(unsigned(BP) + 1);
			when BP_save =>
				BP_temp <= BP;
			when BP_restore =>
				BP <= BP_temp;
			when others =>
				null;
		end case;
 end if;
 end process;

 update_SvPt: process(clk, mb_SvPt)
 begin
	if (rising_edge(clk)) then
		case mb_SvPt is
--			when SvPt_same =>
--				SvPt <= SvPt;
			when SvPt_InLine_start =>
				SvPt <= InLine_Start;
			when SvPt_BP =>
				SvPt <= BP;
			when others =>
				null;
		end case;
 end if;
 end process;
	
-- input buffer pointer
 update_InlEnd: process(clk, mb_InlEnd)
 begin
	if (rising_edge(clk)) then
		case mb_InlEnd is
--			when InLend_same =>
--				InLend <= InLend;
			when InlEnd_InLine_start =>
				InLend <= InLine_Start;
			when InlEnd_inc =>
				InlEnd <= std_logic_vector(unsigned(InlEnd) + 1);
			when InLend_dec =>
				InlEnd <= std_logic_vector(unsigned(InlEnd) - 1);
			when others =>
				null;
		end case;
 end if;
 end process;
	
 -- WARNING: this can easily wrap around and destroy the stack!
 ExpSwapS <= std_logic_vector(unsigned(ExpSP) - 1); 
 ExpSwapR <= std_logic_vector(unsigned(ExpSP) - 1 - unsigned(IL_OP(2 downto 0))); 
 
 -- ExpSP points to first free byte on the stack!
 update_ExpStack: process(clk, mb_ExpStack)
 begin
	if (rising_edge(clk)) then
		case mb_ExpStack is
--			when ExpStack_same =>
--				ExpStack <= ExpStack;
			when ExpStack_clear =>
				ExpStack(0) <= (others => '0');
				ExpSP <= (others => '0');
			when ExpStack_push_T =>
				-- T to next 2 free locations, MSB first
				ExpStack(to_integer(unsigned(ExpSP) + 0)) <= T(15 downto 8);
				ExpStack(to_integer(unsigned(ExpSP) + 1)) <= T(7 downto 0);
				ExpSP <= std_logic_vector(unsigned(ExpSP) + 2);
			when ExpStack_startSwap =>
				SwapS <= ExpStack(to_integer(unsigned(ExpSwapS)));
				SwapR <= ExpStack(to_integer(unsigned(ExpSwapR)));
			when ExpStack_endSwap =>
				ExpStack(to_integer(unsigned(ExpSwapS))) <= SwapR;
				ExpStack(to_integer(unsigned(ExpSwapR))) <= SwapS;
			when ExpStack_push_MDR2 =>
				-- assume it is already uppercased, otherwise a and A would be different variables!
				ExpStack(to_integer(unsigned(ExpSP) + 0)) <= X"00";
				ExpStack(to_integer(unsigned(ExpSP) + 1)) <= MDR(6 downto 0) & '0';
				ExpSP <= std_logic_vector(unsigned(ExpSP) + 2);
			when ExpStack_pop2 => 
				-- combine with assigment to some other 16-bit register
				ExpSP <= std_logic_vector(unsigned(ExpSP) - 2);
			when ExpStack_push_codeByte =>
				ExpStack(to_integer(unsigned(ExpSP) + 0)) <= il_codeByte;
				ExpSP <= std_logic_vector(unsigned(ExpSP) + 1);
			when others =>
				null;
		end case;
 end if;
 end process;
	
-- output port (1 ASCII char at a time, usually goes to UART)
 update_CHAROUT: process(clk, mb_CHAROUT)
 begin
	if (rising_edge(clk)) then
		outchar_send <= CHAROUT_SEND;				-- delay send signal 1 clock cycle
		case mb_CHAROUT is
			when CHAROUT_same =>
				CHAROUT_SEND <= '0';					-- pulse low
				CHAROUT <= CHAROUT;
			when CHAROUT_from_interpreter =>
				CHAROUT_SEND <= '1';					-- pulse high when data loaded
				CHAROUT <= il_codeByte;
			when CHAROUT_from_microcode =>
				CHAROUT_SEND <= '1';					-- pulse high when data loaded
				CHAROUT <= mb_directByte;
			when CHAROUT_from_charin =>
				CHAROUT_SEND <= '1';					-- pulse high when data loaded
				CHAROUT <= CHARIN;
			when CHAROUT_from_MDR =>
				CHAROUT_SEND <= '1';					-- pulse high when data loaded
				CHAROUT <= MDR;
			when CHAROUT_from_YtoAlpha =>
				CHAROUT_SEND <= '1';					-- pulse high when data loaded
				CHAROUT <= hex2ascii(to_integer(unsigned(Y(31 downto 28))));
			when others =>
				null;
		end case;
 end if;
 end process;
 
-- watch the output characters to update the TAB counter
on_charout_send: process(CHAROUT_SEND, reset)
begin
	if (reset = '1') then
		tab_cnt <= (others => '0');
	else
		if (rising_edge(CHAROUT_SEND)) then
			case CHAROUT is
				when CR =>	-- CR resets to left margin
					tab_cnt <= (others => '0');
				when BS => -- BS goes one space left
					tab_cnt <= std_logic_vector(unsigned(tab_cnt) - 1);
				when NUL => -- NULL does nothing
					null;
				when others => -- all other characters advance
					tab_cnt <= std_logic_vector(unsigned(tab_cnt) + 1);
			end case;
		end if;
	end if;
end process; 

-- see http://www.ittybittycomputers.com/IttyBitty/TinyBasic/TinyBasic.c line 776
outchar <= CHAROUT and X"7F";
