update_IL_PC: process(clk, mb_IL_PC)
 begin
	if (rising_edge(clk)) then
		case mb_IL_PC is
--			when IL_PC_same =>
--				IL_PC <= IL_PC;
			when IL_PC_XQhere =>
				IL_PC <= XQhere;
			when IL_PC_inc =>
				IL_PC <= std_logic_vector(unsigned(IL_PC) + 1);
			when IL_PC_T =>
				IL_PC <= T(10 downto 0);
			when IL_PC_pc_plus_off6 =>
				if (IL_OP = OP_SA) then
					-- pc_plus_off8 is the alternative effect to jump to default case
					IL_PC <= std_logic_vector(unsigned(IL_PC) + unsigned(il_codeByte));
				else
					-- a bit bizarre offset
					IL_PC <= std_logic_vector(unsigned(IL_PC) + unsigned(IL_OP) - 96);
				end if;
			when IL_PC_pc_plus_off5 =>
				if (IL_OP = OP_SA) then
					-- pc_plus_off2alpha is the alternative effect for case when MDR is alpha
					IL_PC <= std_logic_vector(unsigned(IL_PC) + (unsigned(MDR) - 65) + (unsigned(MDR) - 65) + 1);
				else
					-- can only jump forward
					IL_PC <= std_logic_vector(unsigned(IL_PC) + unsigned(IL_OFF5));
				end if;
			when IL_PC_direct11 =>
				-- top 3 bits from IL_OP, lower 8 from code pointed by IL
				IL_PC <= IL_OP(2 downto 0) & il_codeByte;
			when IL_PC_RetStack =>
				-- RetSP points to first free location
				-- we cannot modify RetSP here, so must be combined with "pop" operation on RetStack
				IL_PC <= RetStack(to_integer(unsigned(RetSP) - 1))(10 downto 0);
			when others =>
				null;
		end case;
 end if;
end process;

-- holds the start address of Basic input loop (which is 0), or if any program has run, the address of the
-- XQ (execute) instruction. Knowing this entry point is needed to restart program runs
 update_XQhere: process(clk, mb_XQhere)
 begin
	if (rising_edge(clk)) then
	    if (mb_XQhere = XQhere_T) then
		    XQhere <= T(10 downto 0);
	    end if;
 end if;
 end process;

