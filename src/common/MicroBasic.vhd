 update_InlEnd: process(clk, mb_InlEnd)
 begin
	if (rising_edge(clk)) then
		case mb_InlEnd is
--			when InLend_same =>
--				InLend <= InLend;
			when InlEnd_InLine_start =>
				InLend <= InLine_Start;
			when InlEnd_inc =>
				InlEnd <= std_logic_vector(unsigned(InlEnd) + 1);
			when InLend_dec =>
				InlEnd <= std_logic_vector(unsigned(InlEnd) - 1);
			when others =>
				null;
		end case;
 end if;
 end process;
	
 -- WARNING: this can easily wrap around and destroy the stack!
 ExpSwapS <= std_logic_vector(unsigned(ExpSP) - 1); 
 ExpSwapR <= std_logic_vector(unsigned(ExpSP) - 1 - unsigned(IL_OP(2 downto 0))); 
 
 -- ExpSP points to first free lo
 update_ExpStack: process(clk, mb_ExpStack)
 begin
	if (rising_edge(clk)) then
		case mb_ExpStack is
--			when ExpStack_same =>
--				ExpStack <= ExpStack;
			when ExpStack_clear =>
				ExpStack(0) <= (others => '0');
				ExpSP <= (others => '0');
			when ExpStack_push_T =>
				-- T to next 2 free locations, MSB first
				ExpStack(to_integer(unsigned(ExpSP) + 0)) <= T(15 downto 8);
				ExpStack(to_integer(unsigned(ExpSP) + 1)) <= T(7 downto 0);
				ExpSP <= std_logic_vector(unsigned(ExpSP) + 2);
			when ExpStack_startSwap =>
				SwapS <= ExpStack(to_integer(unsigned(ExpSwapS)));
				SwapR <= ExpStack(to_integer(unsigned(ExpSwapR)));
			when ExpStack_endSwap =>
				ExpStack(to_integer(unsigned(ExpSwapS))) <= SwapR;
				ExpStack(to_integer(unsigned(ExpSwapR))) <= SwapS;
			when ExpStack_push_MDR2 =>
				-- assume it is already uppercased, otherwise a and A would be different variables!
				ExpStack(to_integer(unsigned(ExpSP) + 0)) <= X"00";
				ExpStack(to_integer(unsigned(ExpSP) + 1)) <= MDR(6 downto 0) & '0';
				ExpSP <= std_logic_vector(unsigned(ExpSP) + 2);
			when ExpStack_pop2 => 
				-- combine with assigment to some other 16-bit register
				ExpSP <= std_logic_vector(unsigned(ExpSP) - 2);
			when others =>
				null;
		end case;
 end if;
 end process;
	
-- output port (1 ASCII char at a time, usually goes to UART)
 update_CHAROUT: process(clk, mb_CHAROUT)
 begin
	if (rising_edge(clk)) then
		outchar_send <= CHAROUT_SEND;				-- delay send signal 1 clock cycle
		case mb_CHAROUT is
			when CHAROUT_same =>
				CHAROUT_SEND <= '0';					-- pulse low
				CHAROUT <= CHAROUT;
			when CHAROUT_from_interpreter =>
				CHAROUT_SEND <= '1';					-- pulse high when data loaded
				CHAROUT <= il_codeByte;
			when CHAROUT_from_microcode =>
				CHAROUT_SEND <= '1';					-- pulse high when data loaded
				CHAROUT <= mb_directByte;
			when CHAROUT_from_charin =>
				CHAROUT_SEND <= '1';					-- pulse high when data loaded
				CHAROUT <= CHARIN;
			when CHAROUT_from_MDR =>
				CHAROUT_SEND <= '1';					-- pulse high when data loaded
				CHAROUT <= MDR;
			when CHAROUT_from_YtoAlpha =>
				CHAROUT_SEND <= '1';					-- pulse high when data loaded
				CHAROUT <= hex2ascii(to_integer(unsigned(Y(23 downto 20))));
			when others =>
				null;
		end case;
 end if;
 end process;
 
