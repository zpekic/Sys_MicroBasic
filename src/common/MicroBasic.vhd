 -- WARNING: this can easily wrap around and destroy the stack!
 ExpSwapS <= std_logic_vector(unsigned(ExpSP) - 1); 
 ExpSwapR <= std_logic_vector(unsigned(ExpSP) - 1 - unsigned(IL_OP(2 downto 0))); 
 
 -- Stack top value
 ExpSTHi <= ExpStack(to_integer(unsigned(ExpSP) - 2));
 ExpSTLo <= ExpStack(to_integer(unsigned(ExpSP) - 1));

 -- ExpSP points to first free byte on the stack!
 update_ExpStack: process(clk, mb_ExpStack)
 begin
	if (rising_edge(clk)) then
		case mb_ExpStack is
--			when ExpStack_same =>
--				ExpStack <= ExpStack;
			when ExpStack_clear =>
				ExpStack(0) <= (others => '0');
				ExpSP <= (others => '0');
			when ExpStack_push_TWord =>
				-- T to next 2 free locations, MSB first
				ExpStack(to_integer(unsigned(ExpSP) + 0)) <= T(15 downto 8);
				ExpStack(to_integer(unsigned(ExpSP) + 1)) <= T(7 downto 0);
				ExpSP <= std_logic_vector(unsigned(ExpSP) + 2);
			when ExpStack_push_TByte =>
				-- T.LSB to next free location
				ExpStack(to_integer(unsigned(ExpSP) + 0)) <= T(7 downto 0);
				ExpSP <= std_logic_vector(unsigned(ExpSP) + 1);
			when ExpStack_startSwap =>
				SwapS <= ExpStack(to_integer(unsigned(ExpSwapS)));
				SwapR <= ExpStack(to_integer(unsigned(ExpSwapR)));
			when ExpStack_endSwap =>
				ExpStack(to_integer(unsigned(ExpSwapS))) <= SwapR;
				ExpStack(to_integer(unsigned(ExpSwapR))) <= SwapS;
			when ExpStack_pop1 => 
				-- combine with assigment to some other 8-bit register
				ExpSP <= std_logic_vector(unsigned(ExpSP) - 1);
			when ExpStack_pop2 => 
				-- combine with assigment to some other 16-bit register
				ExpSP <= std_logic_vector(unsigned(ExpSP) - 2);
			when others =>
				null;
		end case;
 end if;
 end process;
	
 update_Vars: process(clk, mb_Vars)
 begin
	if (rising_edge(clk)) then
		case mb_Vars is
--			when Vars_same =>
--				Vars <= Vars;
			when Vars_indexFromExpStack =>
				-- top byte on expressions stack (ExpSTLo) contains twice the upper - case ASCII code of the variable name
				vars_index <= std_logic_vector(unsigned('0' & ExpSTLo(7 downto 1)) - X"40");
			when Vars_T =>
				Vars(to_integer(unsigned(vars_index(4 downto 0)))) <= T;
			when others =>
				null;
		end case;
 end if;
 end process;
	
-- output port (1 ASCII char at a time, usually goes to UART)
 update_CHAROUT: process(clk, mb_CHAROUT)
 begin
	if (rising_edge(clk)) then
		outchar_send <= CHAROUT_SEND;				-- delay send signal 1 clock cycle
		case mb_CHAROUT is
			when CHAROUT_same =>
				CHAROUT_SEND <= '0';					-- pulse low
				CHAROUT <= CHAROUT;
			when CHAROUT_from_interpreter =>
				CHAROUT_SEND <= '1';					-- pulse high when data loaded
				CHAROUT <= il_codeByte;
			when CHAROUT_from_microcode =>
				CHAROUT_SEND <= '1';					-- pulse high when data loaded
				CHAROUT <= mb_directByte;
			when CHAROUT_from_charin =>
				CHAROUT_SEND <= '1';					-- pulse high when data loaded
				CHAROUT <= CHARIN;
			when CHAROUT_from_MDR =>
				CHAROUT_SEND <= '1';					-- pulse high when data loaded
				CHAROUT <= MDR;
			when CHAROUT_from_YtoAlpha =>
				CHAROUT_SEND <= '1';					-- pulse high when data loaded
				CHAROUT <= hex2ascii(to_integer(unsigned(Y(31 downto 28))));
			when others =>
				null;
		end case;
 end if;
 end process;
 
-- watch the output characters to update the TAB counter
on_charout_send: process(CHAROUT_SEND, reset)
begin
	if (reset = '1') then
		tab_cnt <= (others => '0');
	else
		if (rising_edge(CHAROUT_SEND)) then
			case CHAROUT is
				when CR =>	-- CR resets to left margin
					tab_cnt <= (others => '0');
				when BS => -- BS goes one space left
					tab_cnt <= std_logic_vector(unsigned(tab_cnt) - 1);
				when NUL => -- NULL does nothing
					null;
				when others => -- all other characters advance
					tab_cnt <= std_logic_vector(unsigned(tab_cnt) + 1);
			end case;
		end if;
	end if;
end process; 

-- see http://www.ittybittycomputers.com/IttyBitty/TinyBasic/TinyBasic.c line 776
outchar <= CHAROUT and X"7F";
 
-- input character
on_inchar_ready: process(reset, inchar_ready, mb_gotChar)
begin
	if ((reset or mb_gotChar) = '1') then
		--CHARIN <= (others => '0');
		charin_ready <= '0';
	else
		if (rising_edge(inchar_ready)) then
			CHARIN <= inchar;
			charin_ready <= '1';
		end if;
	end if;
end process;
	
--------------------------------------------------------------	
-- ALU (including R, S, Y and various bit-state registers)
--------------------------------------------------------------
 update_alu: process(clk, mb_alu)
 begin
	if (rising_edge(clk)) then
		case mb_alu is
--			when alu_nop =>
--				alu <= alu;
			when alu_reset0 =>
				R <= (others => '0');
				S <= (others => '0');
				Y <= (others => '0');
				alu_ready <= '0';
				alu_overflow <= '0';
			when alu_reset1 =>
				R <= (others => '1');
				S <= (others => '0');
				Y <= (others => '0');
				alu_ready <= '0';
				alu_overflow <= '0';
			when alu_R_fromStack =>
				R <= ExpSTHi & ExpSTLo; 
			when alu_S_fromStack =>
				S <= ExpSTHi & ExpSTLo; 
			when alu_S_plus_R =>
				Y <= X"0000" & s_plus_r;
				alu_ready <= '1';
				alu_overflow <= plus_overflow;
			when alu_S_minus_R =>
				Y <= X"0000" & s_minus_r;
				alu_ready <= '1';
				alu_overflow <= minus_overflow;
			when alu_neg_R =>
				Y <= X"0000" & neg_r;
				alu_ready <= '1';
				alu_overflow <= neg_overflow;
			when alu_S_mul_R =>
				Y <= s_mul_r;
				alu_ready <= '1';
				alu_overflow <= mul_overflow;
			when alu_Yx16 =>
				-- microcode should execute this EXACTLY 6 times to pick up 6 BCD digits!
				Y <= Y(27 downto 0) & X"0";	-- shift up by a nibble (== BCD digit)
				if (Y(27 downto 24) = X"0") then
					leading_zero <= leading_zero;
				else
					leading_zero <= '0';
				end if;
			when alu_bcd_start =>
				-- first step
				if (R(15) = '1') then
					alu_sign <= '1';
					R <= neg_R;
				else
					alu_sign <= '0';
				end if;
				S <= (others => '0');	-- prepare counter for bit 0 of R
				Y <= (others => '0');	-- clear BCD accumulator
				alu_ready <= '0';
				alu_overflow <= '0';		-- by implementation can't overflow
			when alu_bcd_next =>
				Y <= bcd_sum & X"00";	-- we care about most significant 6 BCD digits
				if ((S = X"000F") or (R = X"0000")) then
					alu_ready <= '1';
				else
					alu_ready <= '0';
					S <= std_logic_vector(unsigned(S) + 1);
					R <= '0' & R(15 downto 1);	-- shift down
				end if;
				leading_zero <= '1';
			when alu_div_start =>	-- S / R 
				if (S(15) = '0') then
					-- S > 0
					-- NOTE: before this step, R is already checked for 0 (divide by 0 condition)
					if (R(15) = '0') then
						-- R >= 0
						R <= neg_r;	-- we need the -R for subtraction
						alu_sign <= '0';	-- +/+
					else
						-- R < 0, already good for substraction
						alu_sign <= '1';	-- -/+
					end if;
					Y <= X"0000" & S;
				else
					-- S < 0
					if (R(15) = '0') then
						-- R >= 0
						R <= neg_r;	-- we need the -R for subtraction
						alu_sign <= '1';	-- +/-
					else
						-- R < 0
						alu_sign <= '0';	-- -/-
					end if;
					Y <= X"0000" & neg_s;
				end if;				
				alu_overflow <= '0';	-- By definition can't overflow
				alu_ready <= '0';
				S <= X"0010";	-- use S as the 16 steps counter 
			when alu_div_shift =>
				if (S = X"0000") then
					alu_ready <= '1';
				else
					Y <= Y(30 downto 0) & '0'; -- shift remainder and quotient up
					alu_ready <= '0';
				end if;
			when alu_div_subset =>
				if (S = X"0000") then
					alu_ready <= '1';
				else 
					S <= std_logic_vector(unsigned(S) - 1);
					alu_ready <= '0';	-- continue
					if (subc(16) = '0') then
						Y <= Y(31 downto 1) & '0';
					else
						Y <= subc(15 downto 0) & Y(15 downto 1) & '1';
					end if;
				end if;
			when alu_div_end =>
				if (alu_sign = '1') then
					-- correct quotient sign
					Y(15 downto 0) <= neg_y;
				end if;
			when alu_Yx10_plus_MDR =>
				-- used for string to numeric conversion
				Y <=  std_logic_vector((10 * unsigned(Y(15 downto 0))) + (unsigned(MDR) - 48));
				if (Y(31 downto 16) = X"0000") then
					alu_overflow <= '0';
				else
					alu_overflow <= '1';
				end if;
			when alu_Rx256_plus_MDR =>
				-- used for 2 bytes searches in memory
				R <= R(7 downto 0) & MDR;
			when alu_S_fromT =>
				S <= T;
			when alu_R_fromT =>
				R <= T;
			when alu_S_fromLino =>
				S <= Lino;
			when alu_copy_setup =>
				S <= std_logic_vector(unsigned(LE) + 1);
				R <= LS;
				Y <= X"0000" & std_logic_vector(unsigned(PrgEnd) - unsigned(LE));
			when alu_copy_next =>
				S <= std_logic_vector(unsigned(S) + 1);
				R <= std_logic_vector(unsigned(R) + 1);
				Y <= std_logic_vector(unsigned(Y) - 1);
			when alu_ls_load =>
				-- initialize for LS (list) opcode
				-- S = start line, R = end line, store both to Y and check values
				if (unsigned(R) < unsigned(S)) then
					if (S = X"FFFF") then
						ls_params_ok <= '1';
						S <= R;
						Y <= R & R;
					else
						ls_params_ok <= '0';
					end if;
				else
					ls_params_ok <= '1';
					Y <= S & R;
				end if;
			when alu_ls_check =>
				-- check if current line with number R is in range previously saved in Y
				if (unsigned(R) >= unsigned(Y(31 downto 16))) then
					if (unsigned(R) <= unsigned(Y(15 downto 0))) then
						ls_in_range <= '1';
					else
						ls_in_range <= '0';
					end if;
				else
					ls_in_range <= '0';
				end if;
			when others =>
				null;
		end case;
 end if;
 end process;

-- 17 bit subtract for division step
subc <= std_logic_vector(unsigned('0' & Y(31 downto 16)) + unsigned('0' & R));

-- 6 digit BCD adder
adder: entity work.bcdadder Port map (
		power => S(3 downto 0),
		sel => R(0),
		sum_in => Y(31 downto 8),
		sum_out => bcd_sum
		);
 
-- combinatorial operations
s_plus_r <= std_logic_vector(signed(S) + signed(R));
plus_overflow <= ((not R(15)) and (not S(15))) when (s_plus_r(15) = '1') else (R(15) and S(15));

s_minus_r <= std_logic_vector(signed(S) - signed(R));
minus_overflow <= '0';

neg_r <= std_logic_vector(0 - signed(R));
neg_overflow <= '1' when (R = X"8000") else '0';	-- can't negate -32768

neg_s <= std_logic_vector(0 - signed(S));
neg_y <= std_logic_vector(0 - signed(Y(15 downto 0)));

-- will use intrinsic multiplier on FPGA (which is also combinatorial, therefore this is sintesizable)
s_mul_r <= std_logic_vector(signed(R) * signed(S));
mul_pos16 <= '1' when (s_mul_r(31 downto 15) = (X"0000" & '0')) else '0';
mul_neg16 <= '1' when (s_mul_r(31 downto 15) = (X"FFFF" & '1')) else '0';
mul_overflow <= not(mul_pos16 or mul_neg16);

