			debug_t: out STD_LOGIC_VECTOR(15 downto 0);
			debug_sel: in STD_LOGIC_VECTOR(1 downto 0);
			debug_bus : out STD_LOGIC_VECTOR(31 downto 0));
end MicroBasic;

architecture Behavioral of MicroBasic is

-- generics
constant MSB_DOUBLE: positive := (MSB + 1) * 2 - 1;							-- 31 / 63
constant MSB_HALF: positive := (MSB + 1) / 2 - 1;								-- 7 / 15
constant ZERO: std_logic_vector(MSB downto 0) := (others => '0');			-- X"0000" / X"00000000"
constant MINUS_ONE: std_logic_vector(MSB downto 0) := (others => '1');	-- X"FFFF" / X"FFFFFFFF"
constant BITCNT: std_logic_vector(4 downto 0) := std_logic_vector(to_unsigned(MSB, 5));		-- 15 / 31
alias IS_CPU32: std_logic is BITCNT(4);																		-- '0' / '1'
constant STEPCNT: std_logic_vector(7 downto 0) := std_logic_vector(to_unsigned(MSB + 1, 8)); -- X"10" / X"20"
constant BCDDIGITS: positive := (MSB + 9) / 4; 	-- 6 / 10
constant CP_OFF: positive := MSB_HALF + 1;		-- 8 / 16
type ram16xHalf is array (0 to 15) of std_logic_vector(MSB_HALF downto 0);
type ram32xFull is array (0 to 31) of std_logic_vector(MSB downto 0);
type ram8xFull is array(0 to 7) of std_logic_vector(MSB downto 0);
constant INT_VECTORS: ram8xFull := (
	-- Basic line numbers to GOSUB when interrupt levels 0 to 7 are serviced
	std_logic_vector(to_unsigned(0, MSB + 1)),		-- IL = 0, no interrupt
	std_logic_vector(to_unsigned(32100, MSB + 1)),	-- IL = 1, INT
	std_logic_vector(to_unsigned(32200, MSB + 1)),	-- IL = 2, not used
	std_logic_vector(to_unsigned(32300, MSB + 1)),	-- IL = 3, not used
	std_logic_vector(to_unsigned(32400, MSB + 1)),	-- IL = 4, not used
	std_logic_vector(to_unsigned(32500, MSB + 1)),	-- IL = 5, not used
	std_logic_vector(to_unsigned(32600, MSB + 1)),	-- IL = 6, not used 
	std_logic_vector(to_unsigned(32700, MSB + 1))	-- IL = 7, NMI
);


-- control unit
signal ui_address: std_logic_vector(CODE_ADDRESS_WIDTH - 1 downto 0);
signal ui_nextinstr: std_logic_vector(CODE_ADDRESS_WIDTH -1  downto 0);
-- must match the location of the label of same name in the microcode for BUSREQ/BUSACK to work 
constant CHKBUSREQ: std_logic_vector(CODE_ADDRESS_WIDTH - 1 downto 0) := "000001011";

-- Intermediate language
signal IL_PC, XQhere: std_logic_vector(10 downto 0);	-- 9 bits enough, but keep it compatible with other implementations
signal IL_OP: std_logic_vector(7 downto 0);				-- CPU instruction register			
alias IL_OFF5: std_logic_vector(4 downto 0) is IL_OP(4 downto 0);
alias il_codeByte: std_logic_vector(7 downto 0) is IL_D;
signal off_is_zero: std_logic;

-- some IL opcodes that are useful to be known to hardware, not just the microcode
constant OP_GS: std_logic_vector(7 downto 0) := X"14";	-- Go Subroutine (push to Basic return stack)
constant OP_RS: std_logic_vector(7 downto 0) := X"15";	-- ReStore (pop from Basic return stack)
constant OP_GO: std_logic_vector(7 downto 0) := X"16";	-- GO (to)
constant OP_DV: std_logic_vector(7 downto 0) := X"1B";	-- DiVide
constant OP_CP: std_logic_vector(7 downto 0) := X"1C";	-- ComPare
constant OP_NX: std_logic_vector(7 downto 0) := X"1D";	-- NeXt statement
constant OP_NC: std_logic_vector(7 downto 0) := X"1E";	-- Next statement after Colon
constant OP_PQ: std_logic_vector(7 downto 0) := X"21";	-- Print basic string (from RAM to output)
constant OP_GL: std_logic_vector(7 downto 0) := X"27";	-- Get Line
constant OP_RT: std_logic_vector(7 downto 0) := X"2F";	-- ReTurn (pop from IL return stack)
-- extended Tiny Basic specific opcode
constant OP_FS: std_logic_vector(7 downto 0) := X"25";	-- For Start
constant OP_SA: std_logic_vector(7 downto 0) := X"28";	-- Switch on Alpha character

-- single char output
signal CHAROUT: std_logic_vector(7 downto 0);
signal CHAROUT_SEND, CHAROUT_READY, caret_escape, is_pq: std_logic;
signal lz: std_logic := '1';
signal hex_ascii: std_logic_vector(7 downto 0);

-- single char input
signal CHARIN: std_logic_vector(7 downto 0);
signal charin_equ_db, charin_printable, charin_ready, charin_is_break: std_logic; 

-- serial debug port
signal DBGINDEX: std_logic_vector(5 downto 0); -- 64 entries supported
signal DBG_READY, dbg_start: std_logic;

-- external memory interface (stores Basic code and input buffer)
signal MAR: std_logic_vector(15 downto 0);
signal MDR, MDR_UpperCase: std_logic_vector(7 downto 0);
signal mdr_is_num, mdr_is_alpha, mdr_is_lowercase, mdr_is_uppercase: std_logic;
signal mdr_matches_db, mdr_matches_ilcodebyte, mdr_matches_varname, mdr_matches_ilcodebyte_alt_varname: std_logic;

-- key pointers (memory map constants, TODO: make them variable to configure RAM layout and size) 
constant Inline_Start: std_logic_vector(15 downto 0) := X"0000";	-- input buffer at start of RAM
constant Inline_End: std_logic_vector(15 downto 0) := X"007F";		-- input buffer up to 128 characters  	
constant Prog_Start: std_logic_vector(15 downto 0) := X"0080"; 	-- Basic program right after that

-- key pointers (for parsing)
signal BP, BP_saved: std_logic_vector(15 downto 0);
signal SvPt, BE: std_logic_vector(15 downto 0);
signal bp_in_inpline, svp_in_inpline: std_logic;
signal InlEnd, LS, LE, PrgEnd: std_logic_vector(15 downto 0);
signal inlend_max, inlend_min: std_logic;
signal inlend_max_alt_basline_found, inlend_min_alt_impline_empty, basline_found, impline_empty: std_logic;
signal nbusreq_alt_nready: std_logic;

-- expression stack, 32 half-words / 16 words
signal ExpStack: ram16xHalf;
signal ExpSP: std_logic_vector(4 downto 0);			-- stack pointer points to free byte
signal ExpSwapR, ExpSwapS: std_logic_vector(4 downto 0);	-- pointers used in SX IL instruction
signal estack_is_full, estack_is_empty: std_logic;
signal SwapR, SwapS: std_logic_vector(MSB_HALF downto 0);
signal ExpSTHi, ExpSTLo: std_logic_vector(MSB_HALF downto 0);

-- IL return stack (JS / RT)
signal RetStack: ram16x16;
signal RetSP: std_logic_vector(3 downto 0);			-- stack pointer points to free word
signal rstack_is_empty, rstack_is_full: std_logic;

-- Basic stack (GOSUB/RETURN)
signal BasStack: ram16x36;
signal BasSP: std_logic_vector(3 downto 0);			-- stack pointer points to free entry
signal bstack_is_empty, bstack_is_full: std_logic;

-- stack error conditions
signal stack_is_full, stack_is_empty: std_logic;

-- Basic variables A-Z are stored internally in 32*48 RAM, few locations unused
signal vars: ram32xFull;
signal vars_for, vars_next: ram32x16;
signal vars_index, var_name: std_logic_vector(7 downto 0); 	-- 8 bits to make some arithmetic easier
signal var_address: integer range 0 to 31;
signal BasicFor, BasicNext: std_logic_vector(15 downto 0);		
signal BasicVar: std_logic_vector(MSB downto 0);		
signal for_set, next_set: std_logic;
signal for_v: std_logic_vector(31 downto 0)  := (others => '0');
signal next_v: std_logic_vector(31 downto 0) := (others => '0');
signal lino_var: std_logic_vector(15 downto 0) := X"0000";

-- ALU with own internal state
signal bcd_sum: std_logic_vector((BCDDIGITS * 4 - 1) downto 0);	-- 24/40 bits to contain BCD digits e.g. 032767
signal Y, Y_saved: std_logic_vector(MSB_DOUBLE downto 0);			-- double size needed for MUL, DIV, BCD conversion
alias ListFrom: std_logic_vector(MSB downto 0) is Y(MSB_DOUBLE downto (MSB + 1));
alias ListTo: std_logic_vector(MSB downto 0) is Y(MSB downto 0);
alias YHi: std_logic_vector(MSB downto 0) is Y(MSB_DOUBLE downto (MSB + 1));
alias YLo: std_logic_vector(MSB downto 0) is Y(MSB downto 0);
signal R, S: std_logic_vector(MSB downto 0);			-- ALU input arguments are 16 bit
signal s_plus_r, s_minus_r, neg_r, neg_s, neg_ylo, neg_yhi: std_logic_vector(MSB downto 0);
signal t_plus_r, t_minus_s: std_logic_vector(MSB downto 0);
signal s_mul_r: std_logic_vector(MSB_DOUBLE downto 0);		-- output of combinatorial multiplier
signal subc: std_logic_vector((MSB + 1) downto 0);				-- 17 bits, MSB is carry out which is needed in division step 
signal y_zero, r_is_zero: std_logic;								-- combinatorial state of Y and R
signal r_is_zero_full, r_is_zero_16: std_logic;
signal y_zero_alt_cp_skip, cp_skip: std_logic;					-- compare flags
signal alu_sign, alu_overflow, alu_ready, alu_s15: std_logic;	-- state needed for BCD, signed division
alias ls_params_ok: std_logic is alu_ready;
alias ls_in_range: std_logic is alu_sign;
alias ls_passed_end: std_logic is alu_overflow;
signal plus_overflow, minus_overflow, neg_overflow, mul_overflow, mul_pos16, mul_neg16, s_equ_r, s_gt_r: std_logic;

-- Basic line number
signal Lino: std_logic_vector(15 downto 0) := X"0000";
signal Lino_bcd: std_logic_vector(19 downto 0) := X"00000"; -- converted to BCD for tracer only
signal is_runmode, is_runmode_perf: std_logic;		-- 0 for commands, 1 for RUN

-- GOTO cache lookup convenience
alias Lino_index: std_logic_vector(4 downto 0) is Lino(4 downto 0);
alias Lino_tag: std_logic_vector(10 downto 0) is Lino(15 downto 5);

-- built in performance counters while Basic program is running
signal cnt_perf, cnt_perf1000: std_logic_vector(15 downto 0);
signal clk_perf, pulse_fetch, executing_nx, executing_nc: std_logic;

-- interrupts 
signal intreq, y_sign_alt_intreq: std_logic;
signal il_new, il_previous, il_current: std_logic_vector(3 downto 0);
signal lino_int: std_logic_vector(MSB downto 0); -- 32 or 16 bit to make it compatible with ExpStack width

-- GOTO cache - 2-way, 32 entries
signal cache_0, cache_1: ram32x32;
signal cache_v0, cache_v1: std_logic_vector(31 downto 0) := (others => '0');
signal lino_alu: std_logic_vector(15 downto 0);
signal cache_entry0, cache_entry1: std_logic_vector(31 downto 0);
alias cache_tag0: std_logic_vector(10 downto 0) is cache_entry0(15 downto 5); 
alias cache_data0: std_logic_vector(15 downto 0) is cache_entry0(31 downto 16);
alias cache_tag1: std_logic_vector(10 downto 0) is cache_entry1(15 downto 5); 
alias cache_data1: std_logic_vector(15 downto 0) is cache_entry1(31 downto 16);
signal cache_hit: std_logic_vector(1 downto 0);
signal cache_valid: std_logic_vector(1 downto 0);
signal cache_hit_alt_next_set, cache_valid_alt_for_set: std_logic;
signal cache_empty0, cache_empty1, cache_full0, cache_full1: std_logic;
signal cache_store_sel: std_logic;

-- other
signal T, T_saved: std_logic_vector(MSB downto 0);
signal lfsr: std_logic_vector(15 downto 0) := X"FFFF";
signal T_offset: std_logic_vector(15 downto 0);
signal S0, S1, S2: std_logic_vector(MSB downto 0);
signal tab_cnt: std_logic_vector(7 downto 0) := X"00";
signal at_tab: std_logic;
signal ready_alt_break: std_logic;
signal last3Chars: std_logic_vector(23 downto 0);
signal is_notRnd: std_logic;
signal s_equ_db_mod32: std_logic;
signal busack_clk: std_logic;

begin

-- GOTO cache, way 0
cache_empty0 <= '1' when (cache_v0 = X"00000000") else '0';		-- all 32 entries free
cache_full0 <= '1' when (cache_v0 = X"FFFFFFFF") else '0';		-- all 32 entries used
cache_entry0 <= cache_0(to_integer(unsigned(Lino_index)));		-- data/tag cache entry pointed to by Lino 
cache_valid(0) <= cache_v0(to_integer(unsigned(Lino_index)));
cache_hit(0) <= '1' when (cache_tag0 = Lino_tag) else '0';

-- GOTO cache, way 1
cache_empty1 <= '1' when (cache_v1 = X"00000000") else '0';		-- all 32 entries free
cache_full1 <= '1' when (cache_v1 = X"FFFFFFFF") else '0';		-- all 32 entries used
cache_entry1 <= cache_1(to_integer(unsigned(Lino_index)));		-- data/tag cache entry pointed to by Lino 
cache_valid(1) <= cache_v1(to_integer(unsigned(Lino_index)));
cache_hit(1) <= '1' when (cache_tag1 = Lino_tag) else '0';

-- GOTO cache outputs for fun
cache_empty <= cache_empty0 and cache_empty1;
cache_full <= cache_full0 and cache_full1;

-- Basic variable store
var_name <= X"7F" and std_logic_vector(unsigned(vars_index) + X"40");
var_address <= to_integer(unsigned(vars_index(4 downto 0)));
BasicVar <= vars(var_address);
BasicFor <= vars_for(var_address);
BasicNext <= vars_next(var_address);
for_set <= '0' when (BasicFor = X"0000") else for_v(var_address);
next_set <= '0' when (BasicNext = X"0000") else next_v(var_address);

-- Tristate system bus (64k address, bidirectional 8-bit data to Basic RAM "core")
DBUS <= MDR when ((nBUSACK = '1') and (mb_nWR = '0')) else "ZZZZZZZZ";
nRD <= mb_nRD when (nBUSACK = '1') else 'Z';
nWR <= mb_nWR when (nBUSACK = '1') else 'Z';
ABUS <= MAR when (nBUSACK = '1') else "ZZZZZZZZZZZZZZZZ";

busack_clk <= mb_nRD and mb_nWR and (not nBUSREQ);
on_busackclk: process(reset, busack_clk)
begin
	if ((reset = '1') or (nBUSREQ = '1')) then
		nBUSACK <= '1';
	else
		if (rising_edge(busack_clk)) then
			nBUSACK <= '0';
		end if;
	end if;
end process;

update_MAR: process(clk, mb_MAR)
begin
	if (rising_edge(clk)) then
		case mb_MAR is
	--			when MAR_same =>
	--				MAR <= MAR;
			when MAR_InlEnd =>
				MAR <= InlEnd;
			when MAR_BP =>
				MAR <= BP;
			when MAR_T =>
				MAR <= T(15 downto 0);
			when others =>
				null;
		end case;
	end if;
end process;

is_notRnd <= '0' when (last3Chars = X"524E44") else '1';	-- magic number is ASCII for RND
 
update_MDR: process(clk, mb_MDR)
begin
	if (rising_edge(clk)) then
		case mb_MDR is
	--			when MDR_same =>
	--				MDR <= MDR;
			when MDR_from_Bus =>
				MDR <= DBUS;
				-- HACKHACK: track last 3 read chars to compare if they were "RND" - if so, disable overflow check
				if ((unsigned(DBUS) > 96) and (unsigned(DBUS) < 123)) then
					last3Chars <= last3Chars(15 downto 0) & std_logic_vector(unsigned(DBUS) - 32);	-- definitely lowercase
				else
					last3Chars <= last3Chars(15 downto 0) & DBUS;												-- presumed uppercase
				end if;
				-- End hack
			when MDR_zero =>
				MDR <= (others => '0');
			when MDR_CHARIN =>
				MDR <= CHARIN;
			when MDR_ToUpper =>
				-- only touch lowercase a-z and convert to A-Z
				if (mdr_is_lowercase = '1') then
					MDR <= std_logic_vector(unsigned(MDR) - 32);
				end if;
			when MDR_from_SHi =>
				MDR <= S(15 downto 8);
			when MDR_from_SLo =>
				MDR <= S(7 downto 0);
			when MDR_from_microcode =>
				MDR <= '0' & mb_directByte;
			when others =>
				null;
		end case;
	end if;
end process;

-- IL program memory bus (2k address, 8-bit ready only input)
	IL_A <= IL_PC;
-- note that il_op is any data returned by this bus, at instruction fetch this is loaded to IL_OP
-- which is the CPU 8-bit instruction register

-- mapping IL opcode to microcode routine start
mb_instructionstart <= mb_mapper(to_integer(unsigned(il_op)));

-- control unit
cu_mb: entity work.microbasic_control_unit
     Generic map (
			CODE_DEPTH => CODE_ADDRESS_WIDTH,
			IF_WIDTH => CODE_IF_WIDTH
     )
     Port map ( 
			-- standard inputs
			reset => reset,
			clk => clk,
			-- design specific inputs
			seq_cond => mb_seq_cond,
			seq_then => mb_seq_then,
			seq_else => mb_seq_else,
			seq_fork => mb_instructionstart(8 downto 0),	-- IL opcode mapper input
			
			-- condition bits
			cond(seq_cond_true) => '1',
			cond(seq_cond_ILCODEBYTE_BIT7) => il_codebyte(7),
			cond(seq_cond_CHAROUT_READY) => outchar_ready,
			cond(seq_cond_IS_CPU32) => IS_CPU32,
			cond(seq_cond_DBG_READY) => ready_alt_break,
			cond(seq_cond_MDR_MATCHES_DB) => mdr_matches_db,
			cond(seq_cond_NREADY) => (nREADY or (not nBUSACK)),
			cond(seq_cond_INLEND_MAX) => inlend_max_alt_basline_found,
			cond(seq_cond_INLEND_MIN) => inlend_min_alt_impline_empty,
			cond(seq_cond_CHARIN_PRINTABLE) => charin_printable,
			cond(seq_cond_CHARIN_EQU_DB) => charin_equ_db,
			cond(seq_cond_CHARIN_READY) => charin_ready,
			cond(seq_cond_BP_IN_INPLINE) => bp_in_inpline,
			cond(seq_cond_SVP_IN_INPLINE) => svp_in_inpline,
			cond(seq_cond_MDR_IS_NUM) => mdr_is_num,
			cond(seq_cond_MDR_IS_ALPHA) => mdr_is_alpha,
			cond(seq_cond_STACK_IS_FULL) => stack_is_full,
			cond(seq_cond_STACK_IS_EMPTY) => stack_is_empty,
			cond(seq_cond_MDR_MATCHES_ILCODEBYTE) => mdr_matches_ilcodebyte_alt_varname,
			cond(seq_cond_R_IS_ZERO) => r_is_zero,
			cond(seq_cond_Y_ZERO) => y_zero_alt_cp_skip,
			cond(seq_cond_Y_SIGN) => y_sign_alt_intreq,
			cond(seq_cond_ALU_READY) => alu_ready,
			cond(seq_cond_ALU_OVERFLOW) => (overflowEnable and is_notRnd and alu_overflow),
			cond(seq_cond_ALU_SIGN) => alu_sign,
			cond(seq_cond_AT_TAB) => at_tab,
			cond(seq_cond_OFF_IS_ZERO) => off_is_zero,
			cond(seq_cond_IS_RUNMODE) => is_runmode,
			cond(seq_cond_S_EQU_DB_MOD32) => s_equ_db_mod32,	
			cond(seq_cond_CACHE_VALID) => cache_valid_alt_for_set,
			cond(seq_cond_CACHE_HIT) => cache_hit_alt_next_set,
			cond(seq_cond_false) => '0',
			-- outputs
			ui_nextinstr => ui_nextinstr,
			ui_address => ui_address
		);

-- priority encoder to get new external priority level
il_new <= 	"0111" when NMI = '1' else
				-- 5 additional priority layers possible here
				"0001" when INT = '1' else
				"0000";			-- no external signal means no interrupt

-- only react to interrupts while running Basic and of higher priority than current	
update_il: process(clk, reset, clk)
begin
	if ((reset = '1') or (is_runmode = '0')) then
		il_current <= (others => '0');
		il_previous <= (others => '0');
		intreq <= '0';
	else
		if (rising_edge(clk)) then
			if (intreq = '0' and (unsigned(il_new) > unsigned(il_current))) then
				intreq <= '1';
				il_previous <= il_current;
				il_current <= il_new;
			else
				if (INTACK = '1') then
					intreq <= '0';
				end if;
			end if;
			-- pick up previous level if returning from Basic subroutine
			if (mb_BasStack = BasStack_pop) then
				il_current <= BasStack(to_integer(unsigned(BasSP)))(35 downto 32);
			end if;
		end if;
	end if;
end process;

-- GOSUB 32000+(100*il_current) to call interrupt handling Basic subroutine
-- note that at this point il_current should have already captured the "new" level (see above)
lino_int <= INT_VECTORS(to_integer(unsigned(il_current)));

-- few condition codes come from two very different sources, but we can always (?) differentiate
y_sign_alt_intreq <= intreq when (executing_nx = '1') else Y(MSB);

-- simply ignore CTRL/C while the trace output is ongoing
ready_alt_break <= charin_is_break when (DBGINDEX = "000000") else DBG_READY;

-- inlend max and min only used in GL (Get Line, opcode 0x27)
basline_found <= '0' when ((LS = X"0000") or (LE = X"0000")) else '1';
inlend_max_alt_basline_found <= inlend_max when (IL_OP = OP_GL) else basline_found;

impline_empty <= '1' when (BE <= BP) else '0';
inlend_min_alt_impline_empty <= inlend_min when (IL_OP = OP_GL) else impline_empty;

-- Basic condition pass is only meaningful during CP (ComPare, opcode 0x1C) instruction
cp_skip <= (T(CP_OFF + 2) and s_gt_r) or (T(CP_OFF + 1) and s_equ_r) or (T(CP_OFF) and s_minus_r(MSB));
y_zero_alt_cp_skip <= cp_skip when (IL_OP = OP_CP) else y_zero;

-- GOTO cache and FOR/NEXT
cache_valid_alt_for_set <= (cache_valid(0) or cache_valid(1)) when (IL_OP = OP_GO) else for_set;
cache_hit_alt_next_set <= ((cache_hit(0) and cache_valid(0)) or (cache_hit(1) and cache_valid(1))) when (IL_OP = OP_GO) else next_set;

-- other conditional codes
mdr_matches_ilcodebyte_alt_varname <= mdr_matches_varname when (IL_OP = OP_FS) else mdr_matches_ilcodebyte;
mdr_matches_ilcodebyte <= 	'1' when (MDR_UpperCase(6 downto 0) = il_codeByte(6 downto 0)) else '0';
mdr_matches_varname <=		'1' when (MDR_UpperCase(6 downto 0) = var_name(6 downto 0)) else '0';
mdr_matches_db <=				'1' when (MDR_UpperCase(6 downto 0) = mb_directByte) else '0';
--mdr_equ_db <=			'1' when (MDR(6 downto 0) = mb_directByte) else '0';
mdr_is_num <=			'1' when ((unsigned(MDR) > 47) and (unsigned(MDR) < 58)) else '0';
mdr_is_lowercase <=	'1' when ((unsigned(MDR) > 96) and (unsigned(MDR) < 123)) else '0';
mdr_is_uppercase <=	'1' when ((unsigned(MDR) > 64) and (unsigned(MDR) < 91)) else '0';
mdr_is_alpha <= 		mdr_is_lowercase or mdr_is_uppercase;
charin_equ_db <=		'1' when (CHARIN(6 downto 0) = mb_directByte) else '0';
charin_printable <=	'0' when (CHARIN(7 downto 5) = "000") else (not CHARIN(7)); -- TODO: Add 0x7F 
inlend_max <=			'1' when (InlEnd = InLine_End) else '0';
inlend_min <=			'1' when (InlEnd = InLine_Start) else '0';
bp_in_inpline <=		'1' when ((unsigned(BP) >= unsigned(InLine_Start)) and (unsigned(BP) <= unsigned(InLine_End))) else '0';
svp_in_inpline <=		'1' when ((unsigned(SvPt) >= unsigned(InLine_Start)) and (unsigned(SvPt) <= unsigned(InLine_End))) else '0';
at_tab <= 				'1' when (tab_cnt(2 downto 0) = "000") else '0';
r_is_zero <= 			r_is_zero_full when (IL_OP = OP_DV) else r_is_zero_16;					
off_is_zero	<=			'1' when (IL_OFF5 = "00000") else '0';
y_zero <=				'1' when (Y(MSB downto 0) = ZERO) else '0';
is_runmode <=			'0' when (Lino = X"0000") else '1';
s_equ_db_mod32 <=		'1' when (S(4 downto 0) = mb_directByte(4 downto 0)) else '0';

-- for divide instruction check full R to prevent divide by 0, for other operations R is memory address or line number (16 bit)
r_is_zero_full <= 	'1' when (R = ZERO) else '0';
r_is_zero_16 <=		'1' when (R(15 downto 0) = X"0000") else '0';					

-- stack error conditions. Stack pointers point to first empty position. So if SP is 0 can't be pulled from, 
-- and if full (7 or 15) then can't be pushed onto. 
estack_is_full <= 	'1' when (ExpSP = "11111") else '0';
estack_is_empty <=	'1' when (ExpSP = "00000") else '0';
rstack_is_full	<=		'1' when (RetSP = X"F") else '0';
rstack_is_empty <=	'1' when (RetSP = X"0") else '0';
bstack_is_full	<=		'1' when (BasSP = X"F") else '0';
bstack_is_empty <=	'1' when (BasSP = X"0") else '0';

-- we need a "to_upper()" copy of MDR for case insensitive comparison
MDR_UpperCase <= std_logic_vector(unsigned(MDR) - X"20") when (mdr_is_lowercase = '1') else MDR;

-- select right stack condition based on IL_OP (currently executed opcode)
with IL_OP select stack_is_empty <= 
	rstack_is_empty when OP_RT,	-- RT (IL return)
	bstack_is_empty when OP_RS,	-- RS (Basic RETURN)
	estack_is_empty when others;
	
with IL_OP select stack_is_full <= 
	rstack_is_full when X"30" | X"31" | X"32" | X"33" | X"34" | X"35" | X"36" | X"37", -- JS
	bstack_is_full when OP_GS,		-- GS (Basic GOSUB)
	estack_is_full when others;
		
-- get the microcode instruction 
mb_uinstruction <= mb_microcode(to_integer(unsigned(ui_address)));
		
