entity MicroBasic is
		Generic (
			MSB: positive;
			-- TODO: find the actual end of RAM instead of hard coding it here 
			Core_End: std_logic_vector(15 downto 0)
			);
		Port ( 
			reset : in  STD_LOGIC;
			clk : in  STD_LOGIC;
			clk_tick: in STD_LOGIC;
			-- GOTO cache state
			cache_empty : out STD_LOGIC;
			cache_full : out STD_LOGIC;
			-- Intermediate language (IL) read-only memory
			IL_A: out STD_LOGIC_VECTOR(10 downto 0);
			IL_D: in STD_LOGIC_VECTOR(7 downto 0);
			--TB_EXTENDED: in STD_LOGIC;
			-- Input line and Basic program memory (up to 64k)
			nBUSREQ : in STD_LOGIC;
			nBUSACK : buffer STD_LOGIC;
			nREADY: in STD_LOGIC;
			nRD : out STD_LOGIC;
			nWR : out STD_LOGIC;
			ABUS: out STD_LOGIC_VECTOR(15 downto 0);
			DBUS: inout STD_LOGIC_VECTOR(7 downto 0);
			NMI: in STD_LOGIC;
			INT: in STD_LOGIC;
			INTACK: buffer STD_LOGIC;
			-- output char
			outchar: out STD_LOGIC_VECTOR(7 downto 0);
			outchar_send: buffer STD_LOGIC;
			outchar_ready: in STD_LOGIC;
			-- input char
			inchar: in STD_LOGIC_VECTOR(7 downto 0);
			inchar_ready: in STD_LOGIC;
			-- debug / trace UART output
			overflowEnable: in STD_LOGIC;
			traceEnable: in STD_LOGIC;
