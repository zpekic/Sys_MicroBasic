-- counting ticks (typically 1ms) while the program is running (to be displayed at the end of execution
on_clk_tick: process(clk_tick, reset)
begin
	if (reset = '1') then
		cnt_tick <= (others => '0');
		lino_tick <= (others => '0');
	else
		if (rising_edge(clk_tick)) then
			lino_tick <= Lino;
