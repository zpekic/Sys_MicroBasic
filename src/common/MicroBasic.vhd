library IEEE;
use IEEE.STD_LOGIC_1164.ALL;

-- Uncomment the following library declaration if using
-- arithmetic functions with Signed or Unsigned values
use IEEE.NUMERIC_STD.ALL;

-- Uncomment the following library declaration if instantiating
-- any Xilinx primitives in this code.
--library UNISIM;
--use UNISIM.VComponents.all;

use work.microbasic_package.all;
use work.microbasic_code.all;	-- generated by MCC 
use work.microbasic_map.all;	-- generated by MCC

entity MicroBasic is
    Port ( reset : in  STD_LOGIC;
           clk : in  STD_LOGIC;
			  clk_tick: in STD_LOGIC;
			  cond_external: in STD_LOGIC;
			  -- GOTO cache state
			  cache_empty : out STD_LOGIC;
			  cache_full : out STD_LOGIC;
			  -- Intermediate language (IL) read-only memory
			  IL_A: out STD_LOGIC_VECTOR(10 downto 0);
			  IL_D: in STD_LOGIC_VECTOR(7 downto 0);
			  IL_A_VALID: in STD_LOGIC;
			  -- Input line and Basic program memory (up to 64k)
			  nBUSREQ : out STD_LOGIC;
           nBUSACK : in  STD_LOGIC;
			  nRD : out STD_LOGIC;
			  nWR : out STD_LOGIC;
			  ABUS: out STD_LOGIC_VECTOR(15 downto 0);
			  DBUS: inout STD_LOGIC_VECTOR(7 downto 0);
			  -- output char
			  outchar: out STD_LOGIC_VECTOR(7 downto 0);
			  outchar_send: buffer STD_LOGIC;
			  outchar_ready: in STD_LOGIC;
			  -- input char
			  inchar: in STD_LOGIC_VECTOR(7 downto 0);
			  inchar_ready: in STD_LOGIC;
			  -- debug / trace UART output
			  traceEnable: in STD_LOGIC;
           baudrate : in  STD_LOGIC;
           debug_txd : out  STD_LOGIC;
			  debug_t: out STD_LOGIC_VECTOR(15 downto 0);
			  debug_sel: in STD_LOGIC_VECTOR(1 downto 0);
           debug_bus : out STD_LOGIC_VECTOR(31 downto 0));
end MicroBasic;

architecture Behavioral of MicroBasic is

-- control unit
signal ui_address: std_logic_vector(CODE_ADDRESS_WIDTH - 1 downto 0);
signal ui_nextinstr: std_logic_vector(CODE_ADDRESS_WIDTH -1  downto 0);

-- Intermediate language
signal IL_PC, XQhere: std_logic_vector(10 downto 0);	-- 9 bits enough, but keep it compatible with other implementations
signal IL_OP: std_logic_vector(7 downto 0);				-- CPU instruction register			
alias IL_OFF5: std_logic_vector(4 downto 0) is IL_OP(4 downto 0);
alias il_codeByte: std_logic_vector(7 downto 0) is IL_D;
signal off_is_zero: std_logic;
-- some IL opcodes that are useful to be known to hardware, not just the microcode
constant OP_GS: std_logic_vector(7 downto 0) := X"14";	-- Go Subroutine (push to Basic return stack)
constant OP_RS: std_logic_vector(7 downto 0) := X"15";	-- ReStore (pop from Basic return stack)
constant OP_CP: std_logic_vector(7 downto 0) := X"1C";	-- ComPare
constant OP_PQ: std_logic_vector(7 downto 0) := X"21";	-- Print basic string (from RAM to output)
constant OP_GL: std_logic_vector(7 downto 0) := X"27";	-- Get Line
constant OP_RT: std_logic_vector(7 downto 0) := X"2F";	-- ReTurn (pop from IL return stack)

-- single char output
signal CHAROUT: std_logic_vector(7 downto 0);
signal CHAROUT_SEND, CHAROUT_READY, caret_escape, is_pq: std_logic;
signal lz: std_logic := '1';
signal hex_ascii: std_logic_vector(7 downto  0);

-- single char input
signal CHARIN: std_logic_vector(7 downto 0);
signal charin_equ_db, charin_printable, charin_ready, charin_is_break: std_logic; 

-- serial debug port
signal DBGINDEX: std_logic_vector(5 downto 0); -- 64 entries supported
signal DBG_READY, dbg_start: std_logic;

-- external memory interface (stores Basic code and input buffer)
signal MAR: std_logic_vector(15 downto 0);
signal MDR, MDR_UpperCase: std_logic_vector(7 downto 0);
signal mdr_equ_db, mdr_is_num, mdr_is_alpha, mdr_is_lowercase, mdr_is_uppercase, mdr_matches_ilcodebyte: std_logic;

-- key pointers (memory map constants, TODO: make them variable to configure RAM layout and size) 
constant Inline_Start: std_logic_vector(15 downto 0) := X"0000";	-- input buffer at start of RAM
constant Inline_End: std_logic_vector(15 downto 0) := X"00FF";		-- input buffer up to 256 characters  	
constant Prog_Start: std_logic_vector(15 downto 0) := X"0100"; 	-- Basic program right after that
constant Core_End: std_logic_vector(15 downto 0) := X"07FF";		-- up to 2k (but can go up to 64k)
-- key pointers (for parsing)
signal BP, BP_saved: std_logic_vector(15 downto 0);
signal SvPt, BE: std_logic_vector(15 downto 0);
signal bp_in_inpline, svp_in_inpline: std_logic;
signal InlEnd, LS, LE, PrgEnd: std_logic_vector(15 downto 0);
signal inlend_max, inlend_min: std_logic;
signal inlend_max_alt_basline_found, inlend_min_alt_impline_empty, basline_found, impline_empty: std_logic;

-- expression stack, 16 bytes == 8 words
signal ExpStack: ram16x8;
signal ExpSP: std_logic_vector(3 downto 0);			-- stack pointer points to free byte
signal ExpSwapR, ExpSwapS: std_logic_vector(3 downto 0);	-- pointers used in SX IL instruction
signal estack_is_full, estack_is_empty: std_logic;
signal SwapR, SwapS: std_logic_vector(7 downto 0);
signal ExpSTHi, ExpSTLo: std_logic_vector(7 downto 0);

-- IL return stack (JS / RT)
signal RetStack: ram8x16;
signal RetSP: std_logic_vector(2 downto 0);			-- stack pointer points to free word
signal rstack_is_empty, rstack_is_full: std_logic;

-- Basic stack (GOSUB/RETURN)
signal BasStack: ram8x32;
signal BasSP: std_logic_vector(2 downto 0);			-- stack pointer points to free entry
signal bstack_is_empty, bstack_is_full: std_logic;

-- stack error conditions
signal stack_is_full, stack_is_empty: std_logic;

-- Basic variables A-Z are stored internally in 32*16 RAM, few locations unused
signal vars: ram32x16;
signal vars_index: std_logic_vector(7 downto 0); 	-- 8 bits to make some arithmetic easier

-- ALU with own internal state
signal bcd_sum: std_logic_vector(23 downto 0);		-- 24 bits to contain BCD digits e.g. 032767
signal Y, Y_saved: std_logic_vector(31 downto 0);	-- double size needed for MUL, DIV, BCD conversion
alias ListFrom: std_logic_vector(15 downto 0) is Y(31 downto 16);
alias ListTo: std_logic_vector(15 downto 0) is Y(15 downto 0);
signal R, S: std_logic_vector(15 downto 0);			-- ALU input arguments are 16 bit
signal s_plus_r, s_minus_r, r_minus_s, neg_r, neg_s, neg_y: std_logic_vector(15 downto 0);
signal s_mul_r: std_logic_vector(31 downto 0);		-- output of combinatorial multiplier
signal subc: std_logic_vector(16 downto 0);			-- 17 bits, MSB is carry out which is needed in division step 
signal y_zero, r_is_zero: std_logic;					-- combinatorial state of Y and R
signal y_zero_alt_cp_skip, cp_skip: std_logic;		-- compare flags
signal alu_sign, alu_overflow, alu_ready: std_logic;	-- state needed for BCD, signed division
alias ls_params_ok: std_logic is alu_ready;
alias ls_in_range: std_logic is alu_sign;
alias ls_passed_end: std_logic is alu_overflow;
signal plus_overflow, minus_overflow, neg_overflow, mul_overflow, mul_pos16, mul_neg16, s_equ_r, s_gt_r: std_logic;

-- Basic line number
signal Lino: std_logic_vector(15 downto 0) := X"0000";
signal is_runmode: std_logic;		-- 0 for commands, 1 for RUN
-- GOTO cache lookup convenience
alias Lino_index: std_logic_vector(4 downto 0) is Lino(4 downto 0);
alias Lino_tag: std_logic_vector(10 downto 0) is Lino(15 downto 5);

-- built in counter, counts in "ticks" while Basic program is running
signal cnt_tick, cnt_tick_inc: std_logic_vector(31 downto 0);
signal lino_tick: std_logic_vector(15 downto 0);

-- GOTO cache
signal cache: ram32x32;
signal cache_valid: std_logic_vector(31 downto 0) := (others => '0');
signal lino_clk: std_logic_vector(15 downto 0);
signal cache_entry: std_logic_vector(31 downto 0);
alias cache_ttl: std_logic_vector(4 downto 0)  is cache_entry(4 downto 0);
alias cache_tag: std_logic_vector(10 downto 0) is cache_entry(15 downto 5); 
alias cache_data: std_logic_vector(15 downto 0) is cache_entry(31 downto 16);
signal cache_hit: std_logic;

-- other
signal T, T_saved: std_logic_vector(15 downto 0);
signal tab_cnt: std_logic_vector(7 downto 0);
signal at_tab: std_logic;
signal ready_alt_break: std_logic;

begin

-- GOTO cache
cache_empty <= '1' when (cache_valid = X"00000000") else '0';	-- all 32 entries free
cache_full <= '1' when (cache_valid = X"FFFFFFFF") else '0';	-- all 32 entries used
cache_entry <= cache(to_integer(unsigned(Lino_index)));			-- cache entry pointed to by Lino 
cache_hit <= '1' when (cache_tag = Lino_tag) else '0';

-- Tristate system bus (64k address, bidirectional 8-bit data to Basic RAM "core")
nRD <= mb_nRD when (nBUSACK = '0') else 'Z';
nWR <= mb_nWR when (nBUSACK = '0') else 'Z';
-- if read or write request, pull nBUSREQ low, but wait until nBUSACK goes low to proceed
nBUSREQ <= mb_nRD or mb_nWR;

ABUS <= MAR when (nBUSACK = '0') else "ZZZZZZZZZZZZZZZZ";
update_MAR: process(clk, mb_MAR)
begin
	if (rising_edge(clk)) then
		case mb_MAR is
	--			when MAR_same =>
	--				MAR <= MAR;
			when MAR_InlEnd =>
				MAR <= InlEnd;
			when MAR_BP =>
				MAR <= BP;
			when MAR_T =>
				MAR <= T;
			when others =>
				null;
		end case;
	end if;
end process;

DBUS <= MDR when ((mb_nWR or nBUSACK) = '0') else "ZZZZZZZZ";
update_MDR: process(clk, mb_MDR)
begin
	if (rising_edge(clk)) then
		case mb_MDR is
	--			when MDR_same =>
	--				MDR <= MDR;
			when MDR_from_Bus =>
				MDR <= DBUS;
			when MDR_zero =>
				MDR <= (others => '0');
			when MDR_CHARIN =>
				MDR <= CHARIN;
			when MDR_ToUpper =>
				-- only touch lowercase a-z and convert to A-Z
				if (mdr_is_lowercase = '1') then
					MDR <= std_logic_vector(unsigned(MDR) - 32);
				end if;
			when MDR_from_SHi =>
				MDR <= S(15 downto 8);
			when MDR_from_SLo =>
				MDR <= S(7 downto 0);
			when MDR_from_microcode =>
				MDR <= '0' & mb_directByte;
			when others =>
				null;
		end case;
	end if;
end process;

-- IL program memory bus (2k address, 8-bit ready only input)
IL_A <= IL_PC;
-- note that il_op is any data returned by this bus, at instruction fetch this is loaded to IL_OP
-- which is the CPU 8-bit instruction register

-- mapping IL opcode to microcode routine start
mb_instructionstart <= mb_mapper(to_integer(unsigned(il_op)));

-- control unit
cu_mb: entity work.microbasic_control_unit
     Generic map (
			CODE_DEPTH => CODE_ADDRESS_WIDTH,
			IF_WIDTH => CODE_IF_WIDTH
     )
     Port map ( 
			-- standard inputs
			reset => reset,
			clk => clk,
			-- design specific inputs
			seq_cond => mb_seq_cond,
			seq_then => mb_seq_then,
			seq_else => mb_seq_else,
			seq_fork => mb_instructionstart(8 downto 0),	-- IL opcode mapper input
			
			-- condition bits
			cond(seq_cond_true) => '1',
			cond(seq_cond_ILCODEBYTE_BIT7) => il_codebyte(7),
			cond(seq_cond_CHAROUT_READY) => outchar_ready,
			cond(seq_cond_IL_A_VALID) => IL_A_VALID,
			cond(seq_cond_DBG_READY) => ready_alt_break,
			cond(seq_cond_MDR_EQU_DB) => mdr_equ_db,
			cond(seq_cond_nBUSACK) => nBUSACK,
			cond(seq_cond_INLEND_MAX) => inlend_max_alt_basline_found,
			cond(seq_cond_INLEND_MIN) => inlend_min_alt_impline_empty,
			cond(seq_cond_CHARIN_PRINTABLE) => charin_printable,
			cond(seq_cond_CHARIN_EQU_DB) => charin_equ_db,
			cond(seq_cond_CHARIN_READY) => charin_ready,
			cond(seq_cond_BP_IN_INPLINE) => bp_in_inpline,
			cond(seq_cond_SVP_IN_INPLINE) => svp_in_inpline,
			cond(seq_cond_MDR_IS_NUM) => mdr_is_num,
			cond(seq_cond_MDR_IS_ALPHA) => mdr_is_alpha,
			cond(seq_cond_STACK_IS_FULL) => stack_is_full,
			cond(seq_cond_STACK_IS_EMPTY) => stack_is_empty,
			cond(seq_cond_MDR_MATCHES_ILCODEBYTE) => mdr_matches_ilcodebyte,
			cond(seq_cond_R_IS_ZERO) => r_is_zero,
			cond(seq_cond_Y_ZERO) => y_zero_alt_cp_skip,
			cond(seq_cond_Y_SIGN) => Y(15),
			cond(seq_cond_ALU_READY) => alu_ready,
			cond(seq_cond_ALU_OVERFLOW) => alu_overflow,
			cond(seq_cond_ALU_SIGN) => alu_sign,
			cond(seq_cond_AT_TAB) => at_tab,
			cond(seq_cond_OFF_IS_ZERO) => off_is_zero,
			cond(seq_cond_IS_RUNMODE) => is_runmode,
			cond(seq_cond_EXTERNAL) => cond_external,	-- boolean signal from outside of the CPU
			cond(seq_cond_CACHE_VALID) => cache_valid(to_integer(unsigned(Lino_index))),
			cond(seq_cond_CACHE_HIT) => cache_hit,
			cond(seq_cond_false) => '0',
			-- outputs
			ui_nextinstr => ui_nextinstr,
			ui_address => ui_address
		);

-- few condition codes come from two very different sources, but we can always (?) differentiate
-- simply ignore CTRL/C while the trace output is ongoing
ready_alt_break <= charin_is_break when (DBGINDEX = "000000") else DBG_READY;

-- inlend max and min only used in GL (Get Line, opcode 0x27)
basline_found <= '0' when ((LS = X"0000") or (LE = X"0000")) else '1';
inlend_max_alt_basline_found <= inlend_max when (IL_OP = OP_GL) else basline_found;

impline_empty <= '1' when (BE <= BP) else '0';
inlend_min_alt_impline_empty <= inlend_min when (IL_OP = OP_GL) else impline_empty;

-- Basic condition pass is only meaningful during CP (ComPare, opcode 0x1C) instruction
cp_skip <= (T(10) and s_gt_r) or (T(9) and s_equ_r) or (T(8) and s_minus_r(15));
y_zero_alt_cp_skip <= cp_skip when (IL_OP = OP_CP) else y_zero;

mdr_matches_ilcodebyte <= '1' when (MDR_UpperCase(6 downto 0) = il_codeByte(6 downto 0)) else '0';
mdr_equ_db <=			'1' when (MDR(6 downto 0) = mb_directByte) else '0';
mdr_is_num <=			'1' when ((unsigned(MDR) > 47) and (unsigned(MDR) < 58)) else '0';
mdr_is_lowercase <=	'1' when ((unsigned(MDR) > 96) and (unsigned(MDR) < 123)) else '0';
mdr_is_uppercase <=	'1' when ((unsigned(MDR) > 64) and (unsigned(MDR) < 91)) else '0';
mdr_is_alpha <= 		mdr_is_lowercase or mdr_is_uppercase;
charin_equ_db <=		'1' when (CHARIN(6 downto 0) = mb_directByte) else '0';
charin_printable <=	'0' when (CHARIN(7 downto 5) = "000") else (not CHARIN(7)); -- TODO: Add 0x7F 
inlend_max <=			'1' when (InlEnd = InLine_End) else '0';
inlend_min <=			'1' when (InlEnd = InLine_Start) else '0';
bp_in_inpline <=		'1' when ((unsigned(BP) >= unsigned(InLine_Start)) and (unsigned(BP) <= unsigned(InLine_End))) else '0';
svp_in_inpline <=		'1' when ((unsigned(SvPt) >= unsigned(InLine_Start)) and (unsigned(SvPt) <= unsigned(InLine_End))) else '0';
at_tab <= 				'1' when (tab_cnt(2 downto 0) = "000") else '0';
r_is_zero <= 			'1' when (R = X"0000") else '0';
off_is_zero	<=			'1' when (IL_OFF5 = "00000") else '0';
y_zero <=				'1' when (Y(15 downto 0) = X"0000") else '0';
is_runmode <=			'0' when (Lino = X"0000") else '1';

-- stack error conditions. Stack pointers point to first empty position. So if SP is 0 can't be pulled from, 
-- and if full (7 or 15) then can't be pushed onto. 
estack_is_full <= 	'1' when (ExpSP = X"F") else '0';
estack_is_empty <=	'1' when (ExpSP = X"0") else '0';
rstack_is_full	<=		'1' when (RetSP = O"7") else '0';
rstack_is_empty <=	'1' when (RetSP = O"0") else '0';
bstack_is_full	<=		'1' when (BasSP = O"7") else '0';
bstack_is_empty <=	'1' when (BasSP = O"0") else '0';

-- we need a "to_upper()" copy of MDR for case insensitive comparison
MDR_UpperCase <= std_logic_vector(unsigned(MDR) - X"20") when (mdr_is_lowercase = '1') else MDR;

-- select right stack condition based on IL_OP (currently executed opcode)
with IL_OP select stack_is_empty <= 
	rstack_is_empty when OP_RT,	-- RT (IL return)
	bstack_is_empty when OP_RS,	-- RS (Basic RETURN)
	estack_is_empty when others;
	
with IL_OP select stack_is_full <= 
	rstack_is_full when X"30" | X"31" | X"32" | X"33" | X"34" | X"35" | X"36" | X"37", -- JS
	bstack_is_full when OP_GS,		-- GS (Basic GOSUB)
	estack_is_full when others;
		
-- get the microcode instruction 
mb_uinstruction <= mb_microcode(to_integer(unsigned(ui_address)));
		
--------------------------------------------------------------------------------
-- Basic CPU has a program counter, instruction register, internal return stack
--------------------------------------------------------------------------------		
update_IL_PC: process(clk, mb_IL_PC)
 begin
	if (rising_edge(clk)) then
		case mb_IL_PC is
--			when IL_PC_same =>
--				IL_PC <= IL_PC;
			when IL_PC_XQhere =>
				IL_PC <= XQhere;
			when IL_PC_inc =>
				IL_PC <= std_logic_vector(unsigned(IL_PC) + 1);
			when IL_PC_T =>
				IL_PC <= T(10 downto 0);
			when IL_PC_pc_plus_off6 =>
				-- a bit bizarre offset
				IL_PC <= std_logic_vector(unsigned(IL_PC) + unsigned(IL_OP) - 96);
			when IL_PC_pc_plus_off5 =>
				-- can only jump forward
				IL_PC <= std_logic_vector(unsigned(IL_PC) + unsigned(IL_OFF5));
			when IL_PC_direct11 =>
				-- top 3 bits from IL_OP, lower 8 from code pointed by IL
				IL_PC <= IL_OP(2 downto 0) & il_codeByte;
			when IL_PC_RetStack =>
				-- RetSP points to first free location
				-- we cannot modify RetSP here, so must be combined with "pop" operation on RetStack
				IL_PC <= RetStack(to_integer(unsigned(RetSP) - 1))(10 downto 0);
			when others =>
				null;
		end case;
 end if;
end process;

 update_XQhere: process(clk, mb_XQhere)
 begin
	if (rising_edge(clk)) then
	    if (mb_XQhere = XQhere_T) then
		    XQhere <= T(10 downto 0);
	    end if;
 end if;
 end process;

 update_IL_OP: process(clk, mb_IL_OP)
 begin
	if (rising_edge(clk)) then
	    if (mb_IL_OP = IL_OP_from_interpreter) then
		    IL_OP <= il_codeByte;
	    end if;
 end if;
 end process;
		
 update_RetStack: process(clk, mb_RetStack)
 begin
	if (rising_edge(clk)) then
		case mb_RetStack is
--			when RetStack_same =>
--				RetStack <= RetStack;
			when RetStack_clear =>
				RetSP <= (others => '0');
			when RetStack_pop =>
				RetSP <= std_logic_vector(unsigned(RetSP) - 1);
			when RetStack_push_IL_PC_PLUS_1 =>
				RetStack(to_integer(unsigned(RetSP))) <= "00000" & std_logic_vector(unsigned(IL_PC) + 1);
				RetSP <= std_logic_vector(unsigned(RetSP) + 1);
			when others =>
				null;
		end case;
 end if;
 end process;
		
 update_BasStack: process(clk, mb_BasStack)
 begin
	if (rising_edge(clk)) then
		case mb_BasStack is
--			when BasStack_same =>
--				BasStack <= BasStack;
			when BasStack_clear =>
				BasSP <= (others => '0');
			when BasStack_pop =>
				BasSP <= std_logic_vector(unsigned(BasSP) - 1);
			when BasStack_push_Lino_and_BP =>
				BasStack(to_integer(unsigned(BasSP))) <= Lino & BP; 
				BasSP <= std_logic_vector(unsigned(BasSP) + 1);
			when others =>
				null;
		end case;
 end if;
 end process;
		
update_T: process(clk, mb_T)
begin
	if (rising_edge(clk)) then
		case mb_T is
--			when T_same =>
--				T <= T;
			when T_IL_PC =>
				T <= "00000" & IL_PC;
			when T_XQhere =>
				T <= "00000" & XQhere;
			when T_from_vars =>
				T <= vars(to_integer(unsigned(vars_index(4 downto 0))));
			when T_ExpStack =>
				T <= ExpSTHi & ExpSTLo;
			when T_from_YLo =>
				T <= Y(15 downto 0);
			when T_from_YHi =>
				T <= Y(31 downto 16);
			when T_zero =>
				T <= (others => '0');
			when T_codeByte =>
				T <= X"00" & il_codeByte;	
			when T_MDRx2 =>	
				-- assume it is already uppercased, otherwise a and A would be different variables!
				T <= X"00" & MDR(6 downto 0) & '0';
			when T_inc =>
				T <= std_logic_vector(unsigned(T) + 1);
			when T_dec =>
				T <= std_logic_vector(unsigned(T) - 1);
			when T_BP =>
				T <= BP;
			when T_Prog_start =>
				T <= Prog_Start;
			when T_PrgEnd =>
				T <= PrgEnd;	
			when T_from_S =>
				T <= S;
			when T_from_R =>
				T <= R;
			when T_save =>
				T_saved <= T;
			when T_recall =>
				T <= T_saved;
			when T_BasStack_Hi =>
				T <= BasStack(to_integer(unsigned(BasSP) - 1))(31 downto 16);
			when T_BasStack_Lo =>
				T <= BasStack(to_integer(unsigned(BasSP) - 1))(15 downto 0);
			when T_Cache_Data =>
				T <= cache_data;
			when others =>
				null;
		end case;
 end if;
end process;
	
 update_BP: process(clk, mb_BP)
 begin
	if (rising_edge(clk)) then
		case mb_BP is
--			when BP_same =>
--				BP <= BP;
			when BP_InLine_start =>
				BP <= InLine_Start;
			when BP_SvPt =>
				BP <= SvPt;
			when BP_inc =>
				BP <= std_logic_vector(unsigned(BP) + 1);
			when BP_save =>
				BP_saved <= BP;
			when BP_recall =>
				BP <= BP_saved;
			when BP_T =>
				BP <= T;
			when BP_LS =>
				BP <= LS;
			when others =>
