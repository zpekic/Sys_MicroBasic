on_inchar_ready: process(reset, inchar_ready, mb_gotChar)
begin
	if ((reset or mb_gotChar) = '1') then
		--CHARIN <= (others => '0');
		charin_ready <= '0';
		charin_is_break <= '0';
	else
		if (rising_edge(inchar_ready)) then
			CHARIN <= inchar;
			charin_ready <= '1';
			if (inchar = STX) then
				charin_is_break <= '1';
			else
				charin_is_break <= '0';
			end if;
		end if;
	end if;
end process;
	
--------------------------------------------------------------	
-- ALU (including R, S, Y and various bit-state registers)
--------------------------------------------------------------
 update_alu: process(clk, mb_alu)
 begin
	if (rising_edge(clk)) then
		-- clear cache valid bits at start of run (when Lino goes from 0 to some valid Basic line number)
		lino_alu <= Lino;
		if ((is_runmode = '1') and (lino_alu = X"0000")) then
			cache_v0 <= (others => '0');
			cache_v1 <= (others => '0');
			-- pseudo-random number seed
			if (PrgEnd = X"0000") then
				lfsr <= X"FFFF"; 
			else
				lfsr <= PrgEnd;	-- PrgEnd value changes at each Basic program edit 
			end if;
		else
			-- generate another pseudo-random 16-bit value
			lfsr(15) <= lfsr(0);
			lfsr(14) <= lfsr(15);
			lfsr(13) <= lfsr(14) xor lfsr(0);
			lfsr(12) <= lfsr(13) xor lfsr(0);
			lfsr(11) <= lfsr(12);
			lfsr(10) <= lfsr(11) xor lfsr(0);
			lfsr(9 downto 0) <= lfsr(10 downto 1);
		end if;
		case mb_alu is
--			when alu_nop =>
--				alu <= alu;
			when alu_reset0 =>
				R <= (others => '0');
				Y_saved <= (others => '0');
				S <= (others => '0');
				Y <= (others => '0');
				alu_ready <= '0';
				alu_overflow <= '0';
			when alu_reset1 =>
				R(MSB downto 16) <= (others => '0');
				R(15 downto 0) <= (others => '1');
				Y_saved <= (others => '0');
				S <= (others => '0');
				--Y <= (others => '0');
				alu_ready <= '0';
				alu_overflow <= '0';
			when alu_R_fromStack =>
				R <= ExpSTHi & ExpSTLo; 
			when alu_S_fromStack =>
				S <= ExpSTHi & ExpSTLo; 
			when alu_S_plus_R =>
				Y <= ZERO & s_plus_r;
				alu_ready <= '1';
				alu_overflow <= plus_overflow;
			when alu_S_minus_R =>
				Y <= ZERO & s_minus_r;
				alu_ready <= '1';
				alu_overflow <= minus_overflow;
			when alu_neg_R =>
				Y <= ZERO & neg_r;
				alu_ready <= '1';
				alu_overflow <= neg_overflow;
			when alu_S_mul_R =>
				Y <= s_mul_r;
				alu_ready <= '1';
				alu_overflow <= mul_overflow;
			when alu_Yx16 =>
				-- microcode should execute this EXACTLY 7 times to pick up 8 BCD digits!
				Y <= Y((MSB_DOUBLE - 4) downto 0) & X"0";	-- shift up by a nibble (== BCD digit)
			when alu_bcd_start =>
				-- first step
				if (R(MSB) = '1') then
					alu_sign <= '1';
					R <= neg_R;				-- BUGBUG -32768??
				else
					alu_sign <= '0';
				end if;
				S <= (others => '0');	-- prepare counter for bit 0 of R
				Y <= (others => '0');	-- clear BCD accumulator
				alu_ready <= '0';
				alu_overflow <= '0';		-- by implementation can't overflow
			when alu_bcd_next =>
				Y((MSB - 1) downto (BCDDIGITS * 4)) <= (others => '0');	-- 16-bit binary needs 6 BCD digits, so zero out high byte
				Y((BCDDIGITS * 4 - 1) downto 0) <= bcd_sum;	
				if ((S(4 downto 0) = BITCNT) or (R = ZERO)) then
					alu_ready <= '1';
				else
					alu_ready <= '0';
					S <= std_logic_vector(unsigned(S) + 1);
					R <= '0' & R(MSB downto 1);	-- shift down
				end if;
			-- Using restore division without the restoration addition cycle (with sign correction before/after)
			-- See "Digital Computer Arithmetic" by Joseph J.F. Cavanagh, page 254, ISBN 0-07-010282-1
			when alu_div_start =>	-- S / R 
				if (S(MSB) = '0') then
					-- S > 0
					-- NOTE: before this step, R is already checked for 0 (divide by 0 condition)
					if (R(MSB) = '0') then
						-- R >= 0
						R <= neg_r;	-- we need the -R for subtraction
						alu_sign <= '0';	-- +/+
					else
						-- R < 0, already good for substraction
						alu_sign <= '1';	-- -/+
					end if;
					Y <= ZERO & S;
				else
					-- S < 0
					if (R(MSB) = '0') then
						-- R >= 0
						R <= neg_r;	-- we need the -R for subtraction
						alu_sign <= '1';	-- +/-
					else
						-- R < 0
						alu_sign <= '0';	-- -/-
					end if;
					Y <= ZERO & neg_s;
				end if;	
				alu_s15 <= S(MSB);			-- will be used to correct the sign of remainder
				alu_overflow <= '0';		-- By definition can't overflow
				alu_ready <= '0';
				S(MSB downto 8) <= (others => '0');
				S(7 downto 0) <= STEPCNT;	-- use S as the 16 steps counter
			when alu_div_shift =>
				if (S = ZERO) then
					alu_ready <= '1';
				else
					Y <= Y((MSB_DOUBLE - 1) downto 0) & '0'; -- shift remainder and quotient up
					alu_ready <= '0';
				end if;
			when alu_div_subset =>
				if (S = ZERO) then
					alu_ready <= '1';
				else 
					S <= std_logic_vector(unsigned(S) - 1);
					alu_ready <= '0';	-- continue
					if (subc(MSB + 1) = '0') then
						Y <= Y(MSB_DOUBLE downto 1) & '0';
					else
						Y <= subc(MSB downto 0) & Y(MSB downto 1) & '1';
					end if;
				end if;
			when alu_div_end =>
				if (alu_sign = '1') then
					-- correct quotient sign
					YLo <= neg_ylo;
				end if;
				if (alu_s15 = '1') then
					-- correct remainder sign (otherwise remainder would be always positive or zero)
					YHi <= neg_yhi;
				end if;
			when alu_Yx10_plus_MDR =>
				-- used for string to numeric conversion
				Y <=  std_logic_vector((10 * unsigned(Y(MSB downto 0))) + (unsigned(MDR) - 48));
				if (Y(MSB_DOUBLE downto (MSB + 1)) = ZERO) then	-- BUGBUG, this is checked one cycle late
					alu_overflow <= '0';
				else
					alu_overflow <= '1';
				end if;
			when alu_Rx256_plus_MDR =>
				-- used for 2 bytes searches in memory
				R <= R((MSB - 8) downto 0) & MDR;
			when alu_S_fromT =>
				S <= T;
			when alu_R_fromT =>
				R <= T;
			when alu_S_fromLino =>
				S(MSB downto 16) <= (others => '1');
				S(15 downto 0) <= Lino;
			when alu_copy_init_del =>
				S(MSB downto 16) <= (others => '0');
				R(MSB downto 16) <= (others => '0');
				Y(MSB_DOUBLE downto 16) <= (others => '0');
				S(15 downto 0) <= std_logic_vector(unsigned(LE) + 1);
				R(15 downto 0) <= LS;
				Y(15 downto 0) <= std_logic_vector(unsigned(PrgEnd) - unsigned(LE));
			when alu_copy_next =>
				if (unsigned(S) > unsigned(R)) then 
					S <= std_logic_vector(unsigned(S) + 1);
					R <= std_logic_vector(unsigned(R) + 1);
				else 
					S <= std_logic_vector(unsigned(S) - 1);
					R <= std_logic_vector(unsigned(R) - 1);
				end if;
				Y <= std_logic_vector(unsigned(Y) - 1);
			when alu_copy_init_ins =>
				S(MSB downto 16) <= (others => '0');
				R(MSB downto 16) <= (others => '0');
				Y(MSB_DOUBLE downto 16) <= (others => '0');
				S(15 downto 0) <= PrgEnd;
				R(15 downto 0) <= std_logic_vector(unsigned(PrgEnd) + unsigned(BE) - unsigned(BP) + 3);
				Y(15 downto 0) <= std_logic_vector(unsigned(PrgEnd) - unsigned(LS) + 1);
			when alu_ls_load =>
				-- initialize for LS (list) opcode
				-- S = start line, R = end line, store both to Y and check values
				if (S(15 downto 0) = X"FFFF") then
					-- 1 param given on command line, so start and end should be that
					Y <= R & R;				
					ls_params_ok <= '1';					
				else 
					if (R(15 downto 0) = X"FFFF") then
						-- no parameters? assume full range
						Y <= S & R;
						ls_params_ok <= '1';
					else
						-- two or no params on command line, check that start <= end
						if (unsigned(R(15 downto 0)) <= unsigned(S(15 downto 0))) then
							Y <= R & S;
							ls_params_ok <= '1';
						else
							ls_params_ok <= '0';
						end if;
					end if;
				end if;
			when alu_ls_check =>
				-- HACKHACK for 32-bits
				R(MSB downto 16) <= (others => '0');
				-- check if current line with number R is in range previously saved in Y
				if (unsigned(R(15 downto 0)) > unsigned(ListTo)) then
					ls_passed_end <= '1';
					ls_in_range <= '0';
				else
					ls_passed_end <= '0';
					if (unsigned(R(15 downto 0)) >= unsigned(ListFrom)) then
						ls_in_range <= '1';
					else
						ls_in_range <= '0';
					end if;
				end if;
			when alu_Y_save =>
				Y_saved <= Y;
			when alu_Y_recall => 
				Y <= Y_saved;
			when alu_cache_store =>
				-- always write (or overwrite) - see cache_store_sel below for "strategy"
				if (cache_store_sel = '0') then
					cache_0(to_integer(unsigned(Lino_index))) <= BP & Lino;
					cache_v0(to_integer(unsigned(Lino_index))) <= '1';
				else
					cache_1(to_integer(unsigned(Lino_index))) <= BP & Lino;
					cache_v1(to_integer(unsigned(Lino_index))) <= '1';
				end if;
			when alu_for_check =>
				if (t_minus_s = ZERO) then
					alu_ready <= '1';
				else
					alu_ready <= R(MSB) xor (t_minus_s(MSB));
				end if;
			when alu_for_step =>
				Y <= ZERO & t_plus_r;
			when alu_S_swap32 =>
				-- swaps 2 16-bit words if CPU is 32-bit, or NOP for 16-bit 
				S(MSB downto (MSB - 15)) <= S(15 downto 0);
				S(15 downto 0) <= S(MSB downto (MSB - 15));
			when others =>
				null;
		end case;
 end if;
 end process;

with cache_valid select cache_store_sel <= 
	'1' when "01",			-- store to 1 which is free
	'0' when "10",			-- store to 0 which is free
	lfsr(0) when others;	-- select random one to overwrite
	
-- 17 bit subtract for division step
subc <= std_logic_vector(unsigned('0' & Y(MSB_DOUBLE downto (MSB + 1))) + unsigned('0' & R));

-- 6 digit BIN to BCD converter (unsigned)
converter: entity work.bin2bcd 
     Generic map (
			DIGITS => BCDDIGITS)
		Port map (
			power => S(4 downto 0),
			sel => R(0),
			sum_in => Y((BCDDIGITS * 4 - 1) downto 0),
			sum_out => bcd_sum
		);
 
-- combinatorial operations
s_plus_r <= std_logic_vector(signed(S) + signed(R));
plus_overflow <= ((not R(MSB)) and (not S(MSB))) when (s_plus_r(MSB) = '1') else (R(MSB) and S(MSB));
t_plus_r <= std_logic_vector(signed(T) + signed(R));
t_minus_s <= std_logic_vector(signed(T) - signed(S));

s_minus_r <= std_logic_vector(signed(S) - signed(R));
minus_overflow <= '0';
s_equ_r <= '1' when (s_minus_r = ZERO) else '0';
s_gt_r <= not(s_minus_r(MSB)) and not(s_equ_r);

neg_r <= std_logic_vector(0 - signed(R));
neg_overflow <= R(MSB) when (R((MSB - 1) downto 0) = ZERO((MSB - 1) downto 0)) else '0';	-- can't negate -32768

neg_s <= std_logic_vector(0 - signed(S));
neg_ylo <= std_logic_vector(0 - signed(YLo));
neg_yhi <= std_logic_vector(unsigned(YHi xor MINUS_ONE) + 1);

-- will use intrinsic multiplier on FPGA (which is also combinatorial, therefore this is synthesizable)
s_mul_r <= std_logic_vector(signed(R) * signed(S));
mul_pos16 <= '1' when (s_mul_r(MSB_DOUBLE downto MSB) = (ZERO & '0')) else '0';
mul_neg16 <= '1' when (s_mul_r(MSB_DOUBLE downto MSB) = (MINUS_ONE & '1')) else '0';
mul_overflow <= not(mul_pos16 or mul_neg16);

-- Basic line number
 update_Lino: process(clk, mb_Lino)
 begin
	if (rising_edge(clk)) then
	    if (mb_Lino = Lino_T) then
		    Lino <= T(15 downto 0);
	    end if;
 end if;
 end process;

-- End of command in input line
 update_BE: process(clk, mb_BE)
 begin
	if (rising_edge(clk)) then
	    if (mb_BE = BE_T) then
		    BE <= T(15 downto 0);
	    end if;
 end if;
 end process;

-- Start of line in Basic code
 update_LS: process(clk, mb_LS)
 begin
	if (rising_edge(clk)) then
	    if (mb_LS = LS_T) then
		    LS <= T(15 downto 0);
	    end if;
 end if;
 end process;

-- End of line in Basic code
 update_LE: process(clk, mb_LE)
 begin
	if (rising_edge(clk)) then
	    if (mb_LE = LE_T) then
		    LE <= T(15 downto 0);
	    end if;
 end if;
 end process;

-- End of program (points to 2nd of two NULL bytes that are at end of Basic code)
 update_PrgEnd: process(clk, mb_PrgEnd)
 begin
	if (rising_edge(clk)) then
	    if (mb_PrgEnd = PrgEnd_T) then
		    PrgEnd <= T(15 downto 0);
	    end if;
 end if;
 end process;

