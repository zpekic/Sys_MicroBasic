		end case;
 end if;
 end process;
		
update_T: process(clk, mb_T)
begin
	if (rising_edge(clk)) then
		case mb_T is
--			when T_same =>
--				T <= T;
			when T_IL_PC =>
				T(MSB downto 11) <= (others => '0');
				T(10 downto 0) <= IL_PC;
			when T_XQhere =>
				T(MSB downto 11) <= (others => '0');
				T(10 downto 0) <= XQhere;
			when T_from_vars =>
				T <= BasicVar;
			when T_ExpStack =>
				T <= ExpSTHi & ExpSTLo;
			when T_from_YLo =>
				T <= Y(MSB downto 0);
			when T_from_YHi =>
				T <= Y(MSB_DOUBLE downto (MSB + 1));
			when T_zero =>
				T <= (others => '0');
			when T_codeByte =>
				T(MSB downto 8) <= (others => '0');	
				T(7 downto 0) <= il_codeByte;	
			when T_MDR =>	
				T(MSB downto 8) <= (others => '0');
				T(7 downto 0) <= MDR;
			when T_MDRx2 =>	
				-- assume it is already uppercased, otherwise a and A would be different variables!
				T(MSB downto 8) <= (others => '0');
				T(7 downto 0) <= MDR(6 downto 0) & '0';
			when T_inc =>
				T <= std_logic_vector(unsigned(T) + 1);
			when T_dec =>
				T <= std_logic_vector(unsigned(T) - 1);
			when T_BP =>
				T(MSB downto 16) <= (others => '0');
				T(15 downto 0) <= BP;
			when T_Prog_start =>
				T(MSB downto 16) <= (others => '0');
				T(15 downto 0) <= Prog_Start;
			when T_PrgEnd =>
				T(MSB downto 16) <= (others => '0');
				T(15 downto 0) <= PrgEnd;	
			when T_from_S =>
				T <= S;
			when T_from_R =>
				T <= R;
			when T_save =>
				T_saved <= T;
			when T_recall =>
				T <= T_saved;
			when T_BasStack_Hi =>
				T(MSB downto 16) <= (others => '0');
				T(15 downto 0) <= BasStack(to_integer(unsigned(BasSP) - 1))(31 downto 16);
			when T_BasStack_Lo =>
				T(MSB downto 16) <= (others => '0');
				T(15 downto 0) <= BasStack(to_integer(unsigned(BasSP) - 1))(15 downto 0);
			when T_Cache_Data =>
				T(MSB downto 16) <= (others => '0');
				if ((cache_valid(0) and cache_hit(0)) = '1') then
					-- HIT in way 0
					T(15 downto 0) <= cache_data0;
				else
					if ((cache_valid(1) and cache_hit(1)) = '1') then
						-- HIT in way 1
						T(15 downto 0) <= cache_data1;
					else
						-- MISS
						T(15 downto 0) <= (others => '0');
					end if;
				end if;
			when T_LS =>
				T(MSB downto 16) <= (others => '0');
				T(15 downto 0) <= LS;
			when T_binop =>
				-- S	operation
				-- 0	T NOR R
				-- 1	T NOR /R
				-- 2 	/T NOR R
				-- 3	T AND R
				-- 4	T OR S
				-- 5	T OR /S
				-- 6	/T OR S
				-- 7	T NAND R				
				T <= S2 xor ((S1 xor T) nor (S0 xor R));
			when T_fromTicks =>
				T(MSB downto 16) <= (others => '0');
				T(15 downto 0) <= cnt_perf1000;

				T_saved(MSB downto 16) <= (others => '0');
				T_saved(15 downto 0) <= cnt_perf;
			when T_from_var_For =>
				T(MSB downto 16) <= (others => '0');
				T(15 downto 0) <= BasicFor;
			when T_from_var_Next =>
				T(MSB downto 16) <= (others => '0');
				T(15 downto 0) <= BasicNext;
			when T_index2address =>
				T(MSB downto 16) <= (others => '0');
				T(15 downto 0) <= std_logic_vector(unsigned(PrgEnd) + unsigned(T_offset));
			when T_Core_End =>
				-- TODO: CoreEnd should not be a constant!
				T(MSB downto 16) <= (others => '0');
				T(15 downto 0) <= Core_End;		
			when T_from_microcode =>
				T <= ZERO(MSB downto 7) & mb_directByte;
			when T_from_lfsr =>
				T(MSB downto 16) <= (others => '0');
				T(15 downto 0) <= lfsr and X"7FFF";
			when others =>
				null;
		end case;
 end if;
end process;

